// verifyUSBSelectionStartupCleanup checks one cleanup outcome after real selection fails.
//
// Example: a busy resource remains owned until ErrUSBOpen.Close successfully retries it.
func verifyUSBSelectionStartupCleanup(
	t *testing.T,
	failedCleanup bool,
) {
	t.Helper()
	cause := errors.New("descriptor failed")
	peerCause := errors.New("other descriptor failed")
	typed := &os.PathError{Op: "read serial", Path: "peer", Err: cause}
	match := fakeUSBSerialDescriptor{Serial: "wanted"}
	_, _, selectionErr := selectUSBDeviceIndex([]usbSerialDescriptor{fakeUSBSerialDescriptor{Err: typed}, match, fakeUSBSerialDescriptor{Err: peerCause}, match}, "wanted")
	var order []string
	device := &orderedUSBCloser{Name: "device", Order: &order}
	busy := errors.New("device cleanup failed")
	if failedCleanup {
		device.Err = busy
	}
	endpoint := &invalidCountEndpoint{Count: -1}
	session, err := newEndpointSession(endpoint, endpoint, 1024)
	require.NoError(t, err)
	opener := &startupResourcesOpener{Resources: &usbResources{device: device, session: session}, Cause: selectionErr}
	t.Cleanup(
		// releaseStartupResources covers failed assertions before explicit retry verification.
		//
		// Example: a retained device cannot escape the test when an ownership assertion fails.
		func() {
			device.Err = nil
			require.NoError(t, opener.Resources.Close(context.Background()))
		})
	instrument, transport, err := openTestInstrument(t.Context(), Config{Serial: "wanted"}, opener)
	require.Nil(t, instrument)
	require.Nil(t, transport)
	require.Equal(t, 1, opener.Calls)
	require.Zero(t, endpoint.Calls.Load())
	require.ErrorContains(t, err, "multiple OWON USB devices")
	var retained *ErrUSBOpen
	if failedCleanup {
		require.ErrorIs(t, err, busy)
		require.ErrorAs(t, err, &retained)
		require.NotNil(t, retained.backend)
		require.Equal(t, []string{"device"}, order)
		device.Err = nil
		require.NoError(t, retained.Close(t.Context()))
		require.Nil(t, retained.backend)
		require.Equal(t, []string{"device", "device"}, order)
	} else {
		require.False(t, errors.As(err, &retained))
		require.Equal(t, []string{"device"}, order)
	}
	require.ErrorIs(t, err, cause)
	require.ErrorIs(t, err, peerCause)
	require.ErrorIs(t, err, typed)
	var matched *os.PathError
	require.ErrorAs(t, err, &matched)
	require.Same(t, typed, matched)
}

// selectingUSBResourcesOpener runs real serial selection over controlled acquisition inputs.
//
// Example: TCP recovery discovers duplicate serials after observing unreadable peers.
type selectingUSBResourcesOpener struct {
	Descriptors []usbSerialDescriptor
	Resources   *usbResources
	Calls       atomic.Int32
	Configs     []Config
}

// Open returns controlled resources only after running the production descriptor selector.
//
// Example: a failed selection is wrapped by production recovery rather than a fake status mapper.
func (opener *selectingUSBResourcesOpener) Open(
	_ context.Context,
	config Config,
) (*usbResources, error) {
	opener.Calls.Add(1)
	opener.Configs = append(opener.Configs, config)
	_, serial, err := selectUSBDeviceIndex(opener.Descriptors, config.Serial)
	if opener.Resources != nil {
		opener.Resources.serial = serial
	}
	return opener.Resources, err
}

// TestUSBSelectionRecoveryThroughTCP checks discovery failure through the public identity API.
//
// Example: recovery reports every observed peer failure and never sends the pending identity query.
func TestUSBSelectionRecoveryThroughTCP(t *testing.T) {
	first := errors.New("peer one descriptor failed")
	second := errors.New("peer two descriptor failed")
	match := fakeUSBSerialDescriptor{Serial: "wanted"}
	endpoint := &invalidCountEndpoint{Count: -1, Cause: errors.New("initial endpoint failed")}
	oldSession, err := newEndpointSession(endpoint, endpoint, 1024)
	require.NoError(t, err)
	pending := &invalidCountEndpoint{Count: -1}
	nextSession, err := newEndpointSession(pending, pending, 1024)
	require.NoError(t, err)
	opener := &selectingUSBResourcesOpener{
		Descriptors: []usbSerialDescriptor{
			fakeUSBSerialDescriptor{Name: "peer one", Err: first}, match,
			fakeUSBSerialDescriptor{Name: "peer two", Err: second}, match,
		},
		Resources: &usbResources{session: nextSession},
	}
	backend := &Backend{config: (Config{Serial: "wanted"}).withDefaults(), opener: opener, resources: &usbResources{session: oldSession}}
	transport, err := owonsession.New(backend, owonsession.Config{ExpectedSerial: "wanted"})
	require.NoError(t, err)
	t.Cleanup(
		// closeRecoveryTransport releases retained resources after the TCP fixture has joined.
		//
		// Example: failed assertions cannot leave a controlled session owned by the transport.
		func() { require.NoError(t, transport.Close()) })
	instrument, err := owoncontrol.New(transport, owonmodel.DeviceIdentity{})
	require.NoError(t, err)
	client := newSubscribeTCPClient(t, requireNewServer(t, instrument))
	ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
	defer cancel()
	info, err := client.DeviceInfo(ctx)
	require.Nil(t, info)
	require.Equal(t, codes.Unavailable, status.Code(err))
	require.Contains(t, err.Error(), "initial endpoint failed")
	require.Zero(t, opener.Calls.Load())
	info, err = client.DeviceInfo(ctx)
	require.Nil(t, info)
	require.Equal(t, codes.Unavailable, status.Code(err))
	require.EqualValues(t, 1, opener.Calls.Load())
	require.EqualValues(t, 1, endpoint.Calls.Load())
	require.Zero(t, pending.Calls.Load())
	require.Contains(t, err.Error(), "multiple OWON USB devices")
	for _, cause := range []error{first, second} {
		require.Contains(t, err.Error(), cause.Error())
	}
	require.NoError(t, ctx.Err())
	_, recoveryErr := transport.Begin(ctx)
	require.ErrorContains(t, recoveryErr, "recover poisoned session")
	require.EqualValues(t, 2, opener.Calls.Load())
	require.Zero(t, pending.Calls.Load())
	t.Logf("public DeviceInfo: %s; reopen=1 initial transfers=1 pending transfers=0 poison=true", err)
}

// requireNewServer constructs a valid test service or stops the current test.
//
// Example: gRPC harness setup registers its returned server implementation.
func requireNewServer(
	t *testing.T,
	instrument *owoncontrol.Controller,
) *owonserver.Server {
	t.Helper()
	server, err := owonserver.NewServer(instrument)
	require.NoError(t, err)

	return server
}

// newSubscribeTCPClient connects the public client to a production server on a kernel TCP listener.
//
// Example: validation and admission status travel through protobuf and gRPC, with no fake stream context.
func newSubscribeTCPClient(
	t *testing.T,
	service *owonserver.Server,
) *owonclient.Client {
	t.Helper()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	server := grpc.NewServer(owonserver.GRPCServerOptions()...)
	pb.RegisterOwonServiceServer(server, service)
	done := make(chan error, 1)
	observability.Go(t.Context(),
		// serveSubscriptions owns the listener until fixture cleanup stops the server.
		//
		// Example: the buffered result allows shutdown to join without a detached accept loop.
		func(context.Context) { done <- server.Serve(listener) })
	t.Cleanup(
		// stopSubscriptions terminates all handlers and joins the accept loop on failed assertions too.
		//
		// Example: no production goroutine survives the test fixture.
		func() {
			server.Stop()
			require.NoError(t, <-done)
		})
	connection, err := grpc.NewClient(listener.Addr().String(), grpc.WithTransportCredentials(insecure.NewCredentials()))
	require.NoError(t, err)
	t.Cleanup(
		// closeSubscriptionClient releases reconnect ownership before server shutdown.
		//
		// Example: the client connection cannot outlive the test.
		func() { require.NoError(t, connection.Close()) })
	client, err := owonclient.NewClient(connection)
	require.NoError(t, err)
	return client
}
