// TestHandlerCommitsValidStartupFailuresAsSSE verifies valid EventSource requests
// keep the browser-native retry supervisor alive even when Subscribe cannot start.
//
// Example: a temporarily unavailable daemon returns HTTP 200 with a retryable stream-error event.
func TestHandlerCommitsValidStartupFailuresAsSSE(t *testing.T) {
	t.Parallel()

	tests := []struct {
		Name       string
		Service    *fakeService
		WantCode   string
		WantRetry  bool
		WantStatus int
	}{
		{
			Name: "subscribe unavailable",
			Service: &fakeService{
				SubscribeError: status.Error(codes.Unavailable, "daemon unavailable"),
			},
			WantCode:   codes.Unavailable.String(),
			WantRetry:  true,
			WantStatus: http.StatusOK,
		},
		{
			Name: "subscribe internal",
			Service: &fakeService{
				SubscribeError: status.Error(codes.Internal, "stream setup failed"),
			},
			WantCode:   codes.Internal.String(),
			WantRetry:  false,
			WantStatus: http.StatusOK,
		},
		{
			Name: "nil stream",
			Service: &fakeService{
				ReturnNilStream: true,
			},
			WantCode:   codes.Internal.String(),
			WantRetry:  false,
			WantStatus: http.StatusOK,
		},
	}
	for _, test := range tests {
		t.Run(test.Name,
			// checkStartupFailure preserves SSE framing when subscription setup fails.
			//
			// Example: Unavailable remains a retryable stream-error under HTTP 200.
			func(t *testing.T) {
				service := test.Service
				recorder := httptest.NewRecorder()
				service.InitialWriter = recorder
				mustHandler(t, service).ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/api/events", nil))

				require.Equal(t, "retry: 1000\n\n", service.InitialStreamPrefix)
				require.Equal(t, test.WantStatus, recorder.Code)
				require.Equal(t, "text/event-stream", recorder.Header().Get("Content-Type"))
				require.True(t, strings.HasPrefix(recorder.Body.String(), "retry: 1000\n\n"))
				require.Contains(t, recorder.Body.String(), "event: stream-error\n")
				require.Contains(t, recorder.Body.String(), `"code":"`+test.WantCode+`"`)
				require.Contains(t, recorder.Body.String(), `"retryable":`+strconv.FormatBool(test.WantRetry))
			})
	}
}

