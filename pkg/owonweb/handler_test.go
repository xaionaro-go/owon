// Subscribe records the request and returns the configured fake event stream.
//
// Example: SSE tests inject state, waveform, and service-error events through EventStream.
func (service *fakeService) Subscribe(
	ctx context.Context,
	request *pb.SubscribeRequest,
	_ ...grpc.CallOption,
) (grpc.ServerStreamingClient[pb.Event], error) {
	service.SubscribeCalls++
	service.SubscribeRequest = request
	if service.SubscribeStarted != nil {
		close(service.SubscribeStarted)
	}
	if service.InitialWriter != nil {
		service.InitialStreamPrefix = service.InitialWriter.Body.String()
	}
	if service.SubscribeError != nil {
		return nil, service.SubscribeError
	}
	if service.ReturnNilStream {
		return nil, nil
	}
	if service.EventStream == nil {
		return nil, errors.New("stream not configured")
	}
	if eventStream, ok := service.EventStream.(*fakeEventStream); ok {
		eventStream.done = ctx.Done()
	}
	return service.EventStream, nil
}

// fakeEventStream implements a finite server stream for deterministic SSE tests.
// Its private cursor and cancellation signal belong to the active receive lifetime.
//
// Example: events are returned in order and then terminate with io.EOF.
type fakeEventStream struct {
	Events         []*pb.Event
	index          int
	RecvErr        error
	done           <-chan struct{}
	WaitForContext bool
}

// Header returns no initial metadata for the fake stream.
//
// Example: SSE tests focus on event framing rather than gRPC headers.
func (stream *fakeEventStream) Header() (metadata.MD, error) { return nil, nil }

// Trailer returns no terminal metadata for the fake stream.
//
// Example: fake event assertions do not require gRPC trailers.
func (stream *fakeEventStream) Trailer() metadata.MD { return nil }

// CloseSend reports that the fake client has no send side to close.
//
// Example: handler cleanup can call the standard stream method without side effects.
func (stream *fakeEventStream) CloseSend() error { return nil }

// Context returns a background context for the fake stream.
//
// Example: stream consumers can inspect a valid context during tests.
func (stream *fakeEventStream) Context() context.Context { return context.Background() }

// SendMsg accepts no-op client messages for the fake stream interface.
//
// Example: generated gRPC plumbing can call SendMsg without a network transport.
func (stream *fakeEventStream) SendMsg(any) error { return nil }

// RecvMsg accepts no-op server messages for the fake stream interface.
//
// Example: generated gRPC plumbing can call RecvMsg without a network transport.
func (stream *fakeEventStream) RecvMsg(any) error { return nil }

// Recv returns the next configured event or the configured terminal error.
//
// Example: after the final event, Recv returns io.EOF to close an SSE test stream.
func (stream *fakeEventStream) Recv() (*pb.Event, error) {
	if stream.WaitForContext {
		<-stream.done
		return nil, context.Canceled
	}
	if stream.index >= len(stream.Events) {
		if stream.RecvErr != nil {
			return nil, stream.RecvErr
		}
		return nil, io.EOF
	}
	event := stream.Events[stream.index]
	stream.index++
	return event, nil
}

// mustHandler constructs a valid bridge for HTTP behavior tests.
//
// Example: handler setup failures abort a test before requests are made.
func mustHandler(
	t *testing.T,
	client pb.OwonServiceClient,
) http.Handler {
	t.Helper()
	handler, err := NewHandler(client)
	require.NoError(t, err)
	return handler
}
