// Example: adding a new control route cannot silently leave one existing service capability unreachable.
func TestHandlerRoutesEveryServiceMethod(t *testing.T) {
	t.Parallel()

	tests := []struct {
		Name   string
		Method string
		Path   string
		Body   string
	}{
		{Name: "device", Method: http.MethodGet, Path: "/api/device"},
		{Name: "state get", Method: http.MethodGet, Path: "/api/state"},
		{Name: "state post", Method: http.MethodPost, Path: "/api/state", Body: `{}`},
		{Name: "execute", Method: http.MethodPost, Path: "/api/execute", Body: `{"command":"*IDN?","responseMode":"RESPONSE_MODE_ASCII_LINE"}`},
		{Name: "acquisition", Method: http.MethodPost, Path: "/api/acquisition", Body: `{}`},
		{Name: "horizontal", Method: http.MethodPost, Path: "/api/horizontal", Body: `{}`},
		{Name: "trigger", Method: http.MethodPost, Path: "/api/trigger", Body: `{}`},
		{Name: "measurement", Method: http.MethodPost, Path: "/api/measurement", Body: `{}`},
		{Name: "generator", Method: http.MethodPost, Path: "/api/generator", Body: `{}`},
		{Name: "dmm", Method: http.MethodPost, Path: "/api/dmm", Body: `{}`},
		{Name: "dmm measurement", Method: http.MethodGet, Path: "/api/dmm/measurement"},
		{Name: "run", Method: http.MethodPost, Path: "/api/run"},
		{Name: "stop", Method: http.MethodPost, Path: "/api/stop"},
		{Name: "single", Method: http.MethodPost, Path: "/api/single"},
		{Name: "waveform", Method: http.MethodPost, Path: "/api/waveform", Body: `{"channel":"CHANNEL_1","screen":true}`},
	}
	for _, test := range tests {
		t.Run(test.Name,
			// exerciseRoute checks each public HTTP path reaches its typed RPC.
			//
			// Example: a generator JSON patch returns a command result.
			func(t *testing.T) {
				service := &fakeService{}
				recorder := httptest.NewRecorder()
				request := httptest.NewRequest(test.Method, test.Path, strings.NewReader(test.Body))
				mustHandler(t, service).ServeHTTP(recorder, request)
				require.Equal(t, http.StatusOK, recorder.Code)
			})
	}
}

// TestParseHelpersAcceptSupportedNamesAndRejectUnknowns verifies query parsing remains explicit.
//
// Example: both compact and protobuf enum spellings work, while unspecified values fail closed.
func TestParseHelpersAcceptSupportedNamesAndRejectUnknowns(t *testing.T) {
	t.Parallel()

	for _, raw := range []string{"1", "CHANNEL_1", "channel1"} {
		channel, err := parseChannel(raw)
		require.NoError(t, err)
		require.Equal(t, pb.Channel_CHANNEL_1, channel)
	}
	for _, raw := range []string{"2", "CHANNEL_2", "channel2"} {
		channel, err := parseChannel(raw)
		require.NoError(t, err)
		require.Equal(t, pb.Channel_CHANNEL_2, channel)
	}
	_, err := parseChannel("CHANNEL_3")
	require.Error(t, err)

	for _, raw := range []string{
		"UNKNOWN", "MAXIMUM", "MINIMUM", "PEAK_TO_PEAK", "AMPLITUDE", "AVERAGE", "PERIOD", "FREQUENCY",
	} {
		_, err := parseMeasurementKind(raw)
		require.NoError(t, err)
	}
	_, err = parseMeasurementKind("MEASUREMENT_KIND_UNSPECIFIED")
	require.Error(t, err)
}

// TestHTTPStatusCoversGRPCCategories verifies transport errors become useful browser statuses.
//
// Example: ResourceExhausted becomes 429 while an unknown service failure remains 500.
func TestHTTPStatusCoversGRPCCategories(t *testing.T) {
	t.Parallel()

	wants := map[codes.Code]int{
		codes.InvalidArgument:    http.StatusBadRequest,
		codes.Unauthenticated:    http.StatusUnauthorized,
		codes.PermissionDenied:   http.StatusForbidden,
		codes.NotFound:           http.StatusNotFound,
		codes.AlreadyExists:      http.StatusConflict,
		codes.Aborted:            http.StatusConflict,
		codes.ResourceExhausted:  http.StatusTooManyRequests,
		codes.FailedPrecondition: http.StatusPreconditionFailed,
		codes.Unimplemented:      http.StatusNotImplemented,
		codes.DeadlineExceeded:   http.StatusGatewayTimeout,
		codes.Unavailable:        http.StatusServiceUnavailable,
		codes.Internal:           http.StatusInternalServerError,
	}
	for code, want := range wants {
		require.Equal(t, want, httpStatus(code))
	}
}

