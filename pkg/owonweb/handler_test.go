// TestHandlerLifecycleCancellationStopsActiveSSE verifies process cancellation
// reaches an active stream and lets the HTTP handler return promptly.
//
// Example: shutdown does not wait for a browser EventSource that is blocked in Recv.
func TestHandlerLifecycleCancellationStopsActiveSSE(t *testing.T) {
	t.Parallel()

	lifecycleContext, cancelLifecycle := context.WithCancel(context.Background())
	defer cancelLifecycle()
	service := &fakeService{
		EventStream:      &fakeEventStream{WaitForContext: true},
		SubscribeStarted: make(chan struct{}),
	}
	recorder := httptest.NewRecorder()
	done := make(chan struct{})
	observability.Go(context.Background(),
		// serveCancelableRequest exposes stream completion after request cancellation.
		//
		// Example: the process BaseContext can release a handler waiting on Recv.
		func(context.Context) {
			mustHandler(t, service).ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/api/events", nil).WithContext(lifecycleContext))
			close(done)
		})

	select {
	case <-service.SubscribeStarted:
	case <-time.After(time.Second):
		require.FailNow(t, "timed out waiting for the active SSE subscription")
	}
	cancelLifecycle()
	select {
	case <-done:
	case <-time.After(time.Second):
		require.FailNow(t, "handler failed to stop after request cancellation")
	}
	require.Equal(t, http.StatusOK, recorder.Code)
}

