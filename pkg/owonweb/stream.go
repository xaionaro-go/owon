// Browser subscription presentation has defaults separate from core service defaults.
//
// Example: the browser starts with a one-second poll and 128 queued events.
const (
	// defaultWebSubscriptionInterval is the browser's initial polling interval.
	//
	// Example: an omitted browser interval becomes one second.
	defaultWebSubscriptionInterval = time.Second
	// defaultWebSubscriptionCapacity is the browser's initial event count budget.
	//
	// Example: zero API capacity selects 128 events.
	defaultWebSubscriptionCapacity = 128
	// maxSubscribeInterval caps browser polling intervals, not the native service domain.
	//
	// Example: a two-hour browser interval is rejected without limiting direct RPC callers.
	maxSubscribeInterval = time.Hour
)

// handleEvents streams each event within its own bounded write window.
//
// Example: an idle subscription has no write deadline while waiting for Recv.
func (handler *httpHandler) handleEvents(
	writer http.ResponseWriter,
	request *http.Request,
) (_err error) {
	logger.Tracef(request.Context(), "handleEvents")
	defer
	// traceEvents records stream completion without inspecting event payloads.
	//
	// Example: a failed network write is observable when its browser stream ends.
	func() { logger.Tracef(request.Context(), "/handleEvents: %v", _err) }()
	if request.Method != http.MethodGet {
		return methodError(writer, http.MethodGet)
	}
	subscription, err := subscribeRequestFromURL(request)
	if err != nil {
		return writeRPCError(writer, status.Error(codes.InvalidArgument, err.Error()))
	}
	if _, ok := writer.(http.Flusher); !ok {
		return writeRPCError(writer, status.Error(codes.Internal, "SSE streaming is unavailable"))
	}
	writer.Header().Set("Content-Type", "text/event-stream")
	writer.Header().Set("Cache-Control", "no-cache, no-transform")
	writer.Header().Set("Connection", "keep-alive")
	writer.Header().Set("X-Accel-Buffering", "no")
	if err := setWriteDeadline(writer, time.Now().Add(apiTimeout)); err != nil {
		return err
	}
	writer.WriteHeader(http.StatusOK)
	if _, err := io.WriteString(writer, "retry: 1000\n\n"); err != nil {
		return err
	}
	if err := flushEvent(writer); err != nil {
		return err
	}
	streamContext, cancel := context.WithCancel(request.Context())
	defer cancel()
	logger.Debugf(streamContext, "browser subscription started")
	stream, err := handler.client.Subscribe(streamContext, subscription)
	if err != nil && quietStreamEnd(err, streamContext.Err(), false) {
		return nil
	}
	if err != nil {
		return reportStreamFailure(streamContext, writer, err)
	}
	if stream == nil {
		return reportStreamFailure(streamContext, writer, status.Error(codes.Internal, "daemon returned an empty event stream"))
	}
	for {
		event, err := stream.Recv()
		if err != nil && quietStreamEnd(err, streamContext.Err(), true) {
			return nil
		}
		if err != nil {
			return reportStreamFailure(streamContext, writer, err)
		}
		if err := validateEventPayload(event); err != nil {
			return reportStreamFailure(streamContext, writer, err)
		}
		if streamContext.Err() != nil {
			return nil
		}
		payload, err := (protojson.MarshalOptions{UseProtoNames: false}).Marshal(event)
		if err != nil {
			return reportStreamFailure(streamContext, writer, err)
		}
		if len(payload) > maxSSEEventBytes {
			return reportStreamFailure(streamContext, writer, fmt.Errorf("event payload is %d bytes, maximum is %d", len(payload), maxSSEEventBytes))
		}
		if err := setWriteDeadline(writer, time.Now().Add(apiTimeout)); err != nil {
			return err
		}
		if err := writeSSEEvent(writer, eventName(event), event.GetSequence(), payload); err != nil {
			return err
		}
		if err := flushEvent(writer); err != nil {
			return err
		}
	}
}

// quietStreamEnd recognizes only a single expected cause at the subscription boundary.
// Joins remain observable even when one branch resembles EOF or request cancellation.
//
// Example: a live request receiving daemon DeadlineExceeded needs a terminal frame.
func quietStreamEnd(
	cause error,
	requestErr error,
	receiving bool,
) bool {
	for cause != nil {
		if _, joined := cause.(interface {
			// Unwrap exposes independent causes, which cannot be classified as one expected end.
			//
			// Example: errors.Join retains a daemon failure beside cancellation.
			Unwrap() []error
		}); joined {
			return false
		}
		inner := errors.Unwrap(cause)
		if inner == nil {
			break
		}
		cause = inner
	}
	if receiving && cause == io.EOF {
		return true
	}
	if requestErr == nil {
		return false
	}
	if cause == context.Canceled || cause == context.DeadlineExceeded {
		return cause == requestErr
	}
	grpcCause, ok := cause.(interface {
		// GRPCStatus exposes the leaf's actual RPC termination classification.
		//
		// Example: a leaf Canceled status matches a canceled browser request.
		GRPCStatus() *status.Status
	})
	if !ok || grpcCause.GRPCStatus() == nil {
		return false
	}
	switch grpcCause.GRPCStatus().Code() {
	case codes.Canceled:
		return requestErr == context.Canceled
	case codes.DeadlineExceeded:
		return requestErr == context.DeadlineExceeded
	default:
		return false
	}
}

// reportStreamFailure hands an unexpected cause to its remaining observable owner.
//
// Example: after browser cancellation the request logger, not a failed SSE write, owns the error.
func reportStreamFailure(
	ctx context.Context,
	writer http.ResponseWriter,
	cause error,
) error {
	if ctx.Err() != nil {
		return cause
	}
	return finishStream(writer, cause)
}

// flushEvent flushes a frame and clears its deadline before a potentially idle receive.
//
// Example: a minute without events must not leave an expired connection deadline.
func flushEvent(writer http.ResponseWriter) error {
	if err := http.NewResponseController(writer).Flush(); err != nil {
		return err
	}
	return setWriteDeadline(writer, time.Time{})
}

// finishStream writes a terminal frame without changing already committed HTTP headers.
//
// Example: a failed Subscribe preserves EventSource retry semantics.
func finishStream(
	writer http.ResponseWriter,
	cause error,
) error {
	if err := setWriteDeadline(writer, time.Now().Add(apiTimeout)); err != nil {
		return errors.Join(cause, fmt.Errorf("set terminal SSE deadline: %w", err))
	}
	if err := writeSSEError(writer, cause); err != nil {
		return errors.Join(cause, fmt.Errorf("write terminal SSE frame: %w", err))
	}
	if err := flushEvent(writer); err != nil {
		return errors.Join(cause, fmt.Errorf("flush terminal SSE frame and clear deadline: %w", err))
	}
	return nil
}

// eventName maps the protobuf Event oneof to an explicit browser event name.
//
// Example: a service error is emitted as `service-error`, leaving EventSource's
// transport `error` callback available for terminal connection failures.
func eventName(event *pb.Event) string {
	if event == nil {
		return "stream-error"
	}
	switch event.GetPayload().(type) {
	case *pb.Event_State:
		return "state"
	case *pb.Event_Waveform:
		return "waveform"
	case *pb.Event_WaveformGap:
		return "waveform-gap"
	case *pb.Event_Error:
		return "service-error"
	default:
		return "stream-error"
	}
}

// validateEventPayload rejects an incomplete protobuf oneof before marshaling.
//
// Example: a typed-nil Event_State or an Event_State with a nil State becomes
// one terminal stream-error instead of an ambiguous custom SSE event.
func validateEventPayload(event *pb.Event) error {
	if event == nil {
		return invalidEventPayloadError("event is nil")
	}
	switch payload := event.GetPayload().(type) {
	case *pb.Event_State:
		if payload == nil || payload.State == nil {
			return invalidEventPayloadError("state is nil")
		}
	case *pb.Event_Waveform:
		if payload == nil || payload.Waveform == nil {
			return invalidEventPayloadError("waveform is nil")
		}
	case *pb.Event_WaveformGap:
		if payload == nil || payload.WaveformGap == nil {
			return invalidEventPayloadError("waveform gap is nil")
		}
	case *pb.Event_Error:
		if payload == nil || payload.Error == nil {
			return invalidEventPayloadError("service error is nil")
		}
	default:
		return invalidEventPayloadError("unsupported oneof")
	}
	return nil
}

// invalidEventPayloadError classifies malformed daemon events at the web protocol boundary.
//
// Example: callers can use errors.As to retain the public protocol error type while the SSE bridge emits its message.
func invalidEventPayloadError(reason string) error {
	return &ErrInvalidWebProtocol{Reason: fmt.Sprintf("invalid event payload: %s", reason)}
}

// writeSSEEvent writes one bounded SSE frame with a stable sequence id.
//
// Example: reconnecting EventSource clients can use `Last-Event-ID` to report
// the last observed daemon sequence even though replay is not promised.
func writeSSEEvent(
	writer io.Writer,
	name string,
	sequence uint64,
	payload []byte,
) error {
	if strings.ContainsAny(name, "\r\n") {
		return &ErrInvalidWebProtocol{Reason: "SSE event name contains a newline"}
	}
	_, err := fmt.Fprintf(writer, "event: %s\nid: %d\ndata: %s\n\n", name, sequence, payload)
	return err
}

// writeSSEError emits a structured event after SSE headers have been committed.
//
// Example: a failed stream receive becomes a browser-readable `stream-error` event.
func writeSSEError(
	writer io.Writer,
	err error,
) error {
	grpcStatus := status.Convert(err)
	var protocolErr *ErrInvalidWebProtocol
	if errors.As(err, &protocolErr) {
		grpcStatus = status.New(codes.Internal, err.Error())
	}
	payload, marshalErr := json.Marshal(struct {
		Code      string `json:"code"`
		Message   string `json:"message"`
		Retryable bool   `json:"retryable"`
	}{
		Code:      grpcStatus.Code().String(),
		Message:   grpcStatus.Message(),
		Retryable: streamErrorRetryable(grpcStatus.Code()),
	})
	if marshalErr != nil {
		return fmt.Errorf("serialize stream error: %w", marshalErr)
	}
	_, writeErr := fmt.Fprintf(writer, "event: stream-error\ndata: %s\n\n", payload)
	return writeErr
}

// streamErrorRetryable classifies transport failures that the browser should retry.
//
// Example: an unavailable daemon remains eligible for the browser's native reconnect path,
// while ResourceExhausted stays terminal to avoid multiplying capacity pressure.
func streamErrorRetryable(code codes.Code) bool {
	switch code {
	case codes.Aborted, codes.DataLoss, codes.DeadlineExceeded, codes.Unavailable:
		return true
	default:
		return false
	}
}

// subscribeRequestFromURL decodes the EventSource query into a bounded typed subscription.
//
// Example: `?waveform_channel=CHANNEL_1` adds one screen waveform without changing state updates.
func subscribeRequestFromURL(request *http.Request) (*pb.SubscribeRequest, error) {
	if request == nil || request.URL == nil {
		return nil, &ErrInvalidWebRequest{Reason: "subscription request is required"}
	}
	query := request.URL.Query()
	result := &pb.SubscribeRequest{
		IncludeScreenHeader: false,
		IncludeControls:     true,
		Measurements:        nil,
		WaveformChannels:    nil,
	}
	includeScreenHeader, err := parseBoolDefault(query.Get("include_screen_header"), false)
	if err != nil {
		return nil, err
	}
	includeControls, err := parseBoolDefault(query.Get("include_controls"), true)
	if err != nil {
		return nil, err
	}
	result.IncludeScreenHeader = includeScreenHeader
	result.IncludeControls = includeControls
	if raw := query.Get("request"); raw != "" {
		if len(raw) > maxSubscribeQuery {
			return nil, &ErrInvalidWebRequest{Reason: fmt.Sprintf("request query exceeds %d bytes", maxSubscribeQuery)}
		}
		if err := (protojson.UnmarshalOptions{DiscardUnknown: false}).Unmarshal([]byte(raw), result); err != nil {
			return nil, &ErrInvalidWebRequest{Reason: "decode request query", Cause: err}
		}
	}
	if raw := query.Get("interval"); raw != "" {
		interval, err := time.ParseDuration(raw)
		if err != nil {
			return nil, &ErrInvalidWebRequest{Reason: "interval must be a duration", Cause: err}
		}
		result.Interval = durationpb.New(interval)
	}
	if raw := query.Get("queue_capacity"); raw != "" {
		capacity, err := strconv.ParseUint(raw, 10, 32)
		if err != nil {
			return nil, &ErrInvalidWebRequest{Reason: "queue_capacity must be an unsigned 32-bit integer", Cause: err}
		}
		result.QueueCapacity = uint32(capacity)
	}
	for _, raw := range query["waveform_channel"] {
		channel, err := parseChannel(raw)
		if err != nil {
			return nil, err
		}
		result.WaveformChannels = append(result.WaveformChannels, channel)
	}
	for _, raw := range query["measurement"] {
		parts := strings.Split(raw, ":")
		if len(parts) != 2 {
			return nil, &ErrInvalidWebRequest{Reason: "measurement must be CHANNEL:MEASUREMENT_KIND"}
		}
		channel, err := parseChannel(parts[0])
		if err != nil {
			return nil, err
		}
		kind, err := parseMeasurementKind(parts[1])
		if err != nil {
			return nil, err
		}
		result.Measurements = append(result.Measurements, &pb.MeasurementSelector{Channel: channel, Kind: kind})
	}
	applyWebSubscribeDefaults(result)
	if err := validateWebSubscribeRequest(result); err != nil {
		return nil, err
	}
	return result, nil
}

// applyWebSubscribeDefaults normalizes only omitted fields on a locally owned request.
//
// Example: JSON reset booleans remain untouched while a nil interval gets the browser default.
func applyWebSubscribeDefaults(request *pb.SubscribeRequest) {
	if request.Interval == nil {
		request.Interval = durationpb.New(defaultWebSubscriptionInterval)
	}
	if request.QueueCapacity == 0 {
		request.QueueCapacity = defaultWebSubscriptionCapacity
	}
}

// validateWebSubscribeRequest adds browser policy to the shared pure service validator.
//
// Example: two hours is valid for direct RPC but rejected by this browser boundary.
func validateWebSubscribeRequest(request *pb.SubscribeRequest) error {
	if err := owonrpc.ValidateSubscribeRequest(request); err != nil {
		return &ErrInvalidWebRequest{Reason: "invalid subscription", Cause: err}
	}
	if request.Interval != nil && request.Interval.AsDuration() > maxSubscribeInterval {
		return &ErrInvalidWebRequest{Reason: fmt.Sprintf("interval exceeds browser maximum %s", maxSubscribeInterval)}
	}
	return nil
}

// parseBoolDefault parses optional EventSource booleans while keeping a useful default.
//
// Example: an omitted `include_controls` query uses the caller's default while `false` remains explicit.
func parseBoolDefault(
	raw string,
	fallback bool,
) (bool, error) {
	if raw == "" {
		return fallback, nil
	}
	value, err := strconv.ParseBool(raw)
	if err != nil {
		return false, &ErrInvalidWebRequest{Reason: fmt.Sprintf("boolean query value %q is invalid", raw), Cause: err}
	}
	return value, nil
}

// parseChannel accepts symbolic protobuf names and compact browser-friendly numbers.
//
// Example: both `CHANNEL_1` and `1` select channel one.
func parseChannel(raw string) (pb.Channel, error) {
	switch strings.ToUpper(strings.TrimSpace(raw)) {
	case "1", "CHANNEL_1", "CHANNEL1":
		return pb.Channel_CHANNEL_1, nil
	case "2", "CHANNEL_2", "CHANNEL2":
		return pb.Channel_CHANNEL_2, nil
	default:
		return pb.Channel_CHANNEL_UNSPECIFIED, &ErrInvalidWebRequest{Reason: fmt.Sprintf("unsupported channel %q", raw)}
	}
}

// parseMeasurementKind accepts symbolic protobuf names used by event-stream selectors.
//
// Example: `FREQUENCY` selects the frequency measurement kind.
func parseMeasurementKind(raw string) (pb.MeasurementKind, error) {
	switch strings.ToUpper(strings.TrimSpace(raw)) {
	case "MEASUREMENT_KIND_UNKNOWN", "UNKNOWN":
		return pb.MeasurementKind_MEASUREMENT_KIND_UNKNOWN, nil
	case "MEASUREMENT_KIND_MAXIMUM", "MAXIMUM":
		return pb.MeasurementKind_MEASUREMENT_KIND_MAXIMUM, nil
	case "MEASUREMENT_KIND_MINIMUM", "MINIMUM":
		return pb.MeasurementKind_MEASUREMENT_KIND_MINIMUM, nil
	case "MEASUREMENT_KIND_PEAK_TO_PEAK", "PEAK_TO_PEAK":
		return pb.MeasurementKind_MEASUREMENT_KIND_PEAK_TO_PEAK, nil
	case "MEASUREMENT_KIND_AMPLITUDE", "AMPLITUDE":
		return pb.MeasurementKind_MEASUREMENT_KIND_AMPLITUDE, nil
	case "MEASUREMENT_KIND_AVERAGE", "AVERAGE":
		return pb.MeasurementKind_MEASUREMENT_KIND_AVERAGE, nil
	case "MEASUREMENT_KIND_PERIOD", "PERIOD":
		return pb.MeasurementKind_MEASUREMENT_KIND_PERIOD, nil
	case "MEASUREMENT_KIND_FREQUENCY", "FREQUENCY":
		return pb.MeasurementKind_MEASUREMENT_KIND_FREQUENCY, nil
	default:
		return pb.MeasurementKind_MEASUREMENT_KIND_UNSPECIFIED, &ErrInvalidWebRequest{Reason: fmt.Sprintf("unsupported measurement kind %q", raw)}
	}
}
