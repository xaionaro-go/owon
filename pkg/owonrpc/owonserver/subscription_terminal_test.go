// TestSubscriptionBudgetRejectsUnownedRelease verifies accounting bugs cannot silently create spare capacity.
//
// Example: an oversized or negative release panics without changing the valid outstanding charge.
func TestSubscriptionBudgetRejectsUnownedRelease(t *testing.T) {
	budget := newSubscriptionBudget(10)
	require.True(t, budget.reserve(5))
	for _, size := range []int{-1, 6} {
		require.Panics(t,
			// releaseInvalidCharge exercises a programmer-error boundary, not a device input.
			//
			// Example: releasing six bytes after reserving five must not clamp the balance to zero.
			func() { budget.release(size) })
		require.Equal(t, int64(5), budget.used.Load())
	}
	budget.release(5)
	require.Zero(t, budget.used.Load())
	budget.release(0)
	require.Zero(t, budget.used.Load())
}

// TestTerminalMetadataAfterRealBytePressure verifies draining real payloads releases the local byte budget.
//
// Example: nearly 64 MiB of waveforms do not prevent a later gap and terminal event from being delivered.
func TestTerminalMetadataAfterRealBytePressure(t *testing.T) {
	budget := newSubscriptionBudget(maximumSubscriptionBytes)
	queue, err := newSubscriptionQueueWithBudget(3, budget)
	require.NoError(t, err)
	defer queue.close()
	for sequence := uint64(1); sequence <= 3; sequence++ {
		length := 31 << 20
		if sequence == 3 {
			length = maximumSubscriptionBytes - queue.bytes - 128
		}
		require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: pb.Channel_CHANNEL_1, Sequence: sequence, Data: make([]byte, length)}}}))
	}
	require.Less(t, maximumSubscriptionBytes-queue.bytes, 128)
	require.Equal(t, int64(queue.bytes), budget.used.Load())
	require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: pb.Channel_CHANNEL_1, Sequence: 4}}}))
	cause := errors.New("offline")
	queue.finish(&pb.Event{Payload: &pb.Event_Error{Error: &pb.ServiceError{Message: strings.Repeat("x", 1024)}}}, cause)
	for sequence := uint64(1); sequence <= 5; sequence++ {
		event, err := queue.next(t.Context())
		require.NoError(t, err)
		require.Equal(t, sequence, event.Sequence)
		switch sequence {
		case 1, 2, 3:
			require.Equal(t, sequence, event.GetWaveform().Sequence)
		case 4:
			require.Equal(t, uint64(4), event.GetWaveformGap().FirstMissingSequence)
		case 5:
			require.Len(t, event.GetError().Message, 1024)
		}
	}
	_, err = queue.next(t.Context())
	require.ErrorIs(t, err, cause)
	require.Zero(t, budget.used.Load())
	require.Nil(t, queue.events)
}

// TestTerminalAdmissionFailureRetainsOwner verifies external pressure and oversize fail without phantom publication.
//
// Example: closing the failed queue clears staging but cannot release another subscriber's charge.
func TestTerminalAdmissionFailureRetainsOwner(t *testing.T) {
	for _, oversized := range []bool{false, true} {
		budget := newSubscriptionBudget(1024)
		external, err := newSubscriptionQueueWithBudget(1, budget)
		require.NoError(t, err)
		if !oversized {
			event := &pb.Event{Payload: &pb.Event_State{State: &pb.StateSnapshot{ScreenHeaderJson: make([]byte, 900)}}}
			require.NoError(t, external.enqueueState(event))
			budget.limit = int(budget.used.Load())
		}
		queue, err := newSubscriptionQueueWithBudget(1, budget)
		require.NoError(t, err)
		message := "failure"
		if oversized {
			message = strings.Repeat("x", maximumSubscriptionEventBytes)
		}
		terminal := &pb.Event{Payload: &pb.Event_Error{Error: &pb.ServiceError{Message: message}}}
		cause := errors.New("device failed")
		queue.finish(terminal, cause)
		event, err := queue.next(t.Context())
		require.Nil(t, event)
		require.ErrorIs(t, err, cause)
		requireErrorType[*ErrSubscriptionResourceExhausted](t, err)
		require.Same(t, terminal, queue.terminalEvent)
		require.Zero(t, queue.nextPublication)
		queue.close()
		require.Nil(t, queue.terminalEvent)
		require.Equal(t, int64(external.bytes), budget.used.Load())
		external.close()
		require.Zero(t, budget.used.Load())
	}
	queue, err := newSubscriptionQueue(1)
	require.NoError(t, err)
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	event, err := queue.next(ctx)
	require.Nil(t, event)
	require.ErrorIs(t, err, context.Canceled)
	queue.close()
	_, err = queue.next(t.Context())
	require.ErrorIs(t, err, io.EOF)
}

// TestTerminalGapFailureRetainsOwner verifies a blocked gap stays unpublished until final close.
//
// Example: another subscriber holding all shared bytes cannot make this queue lose its staged loss summary.
func TestTerminalGapFailureRetainsOwner(t *testing.T) {
	budget := newSubscriptionBudget(1024)
	external, err := newSubscriptionQueueWithBudget(1, budget)
	require.NoError(t, err)
	defer external.close()
	require.NoError(t, external.enqueueState(&pb.Event{Payload: &pb.Event_State{State: &pb.StateSnapshot{}}}))
	budget.limit = int(budget.used.Load())
	queue, err := newSubscriptionQueueWithBudget(1, budget)
	require.NoError(t, err)
	queue.recordDropLocked(pb.Channel_CHANNEL_1, 7)
	terminal := &pb.Event{Payload: &pb.Event_Error{Error: &pb.ServiceError{Message: "offline"}}}
	cause := errors.New("offline")
	queue.finish(terminal, cause)
	for range 2 {
		event, err := queue.next(t.Context())
		require.Nil(t, event)
		require.ErrorIs(t, err, cause)
		requireErrorType[*ErrSubscriptionResourceExhausted](t, err)
		require.Same(t, terminal, queue.terminalEvent)
		require.Len(t, queue.drops, 1)
		require.Zero(t, queue.nextPublication)
	}
	queue.close()
	require.Nil(t, queue.terminalEvent)
	require.Empty(t, queue.drops)
	require.Equal(t, int64(external.bytes), budget.used.Load())
	external.close()
	require.Zero(t, budget.used.Load())
}

// TestTerminalMetadataAfterFullFIFO verifies retained waveforms release capacity before terminal admission.
//
// Example: a full 1024-event queue drains before two ordered channel gaps and a final error.
func TestTerminalMetadataAfterFullFIFO(t *testing.T) {
	queue, err := newSubscriptionQueueWithBudget(owonrpc.MaximumSubscriptionCapacity, newSubscriptionBudget(maximumSubscriptionBytes))
	require.NoError(t, err)
	defer queue.close()
	for sequence := uint64(1); sequence <= owonrpc.MaximumSubscriptionCapacity; sequence++ {
		require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: pb.Channel_CHANNEL_1, Sequence: sequence}}}))
	}
	for _, channel := range []pb.Channel{pb.Channel_CHANNEL_2, pb.Channel_CHANNEL_1} {
		require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: channel, Sequence: 1025}}}))
	}
	cause := errors.New("device offline")
	queue.finish(&pb.Event{Payload: &pb.Event_Error{Error: &pb.ServiceError{Message: cause.Error()}}}, cause)
	for sequence := uint64(1); sequence <= owonrpc.MaximumSubscriptionCapacity; sequence++ {
		event, err := queue.next(t.Context())
		require.NoError(t, err)
		require.Equal(t, sequence, event.Sequence)
		require.Equal(t, sequence, event.GetWaveform().Sequence)
	}
	for index, channel := range []pb.Channel{pb.Channel_CHANNEL_1, pb.Channel_CHANNEL_2} {
		event, err := queue.next(t.Context())
		require.NoError(t, err)
		require.Equal(t, uint64(owonrpc.MaximumSubscriptionCapacity+index+1), event.Sequence)
		require.True(t, proto.Equal(&pb.WaveformGap{Channel: channel, FirstMissingSequence: 1025, LastMissingSequence: 1025, MissingCount: 1}, event.GetWaveformGap()))
	}
	event, err := queue.next(t.Context())
	require.NoError(t, err)
	require.Equal(t, uint64(owonrpc.MaximumSubscriptionCapacity+3), event.Sequence)
	require.Equal(t, cause.Error(), event.GetError().Message)
	event, err = queue.next(t.Context())
	require.Nil(t, event)
	require.ErrorIs(t, err, cause)
	require.Zero(t, queue.budget.used.Load())
	require.Nil(t, queue.terminalEvent)
	require.Empty(t, queue.drops)
}

// TestTerminalMetadataUsesOneSharedCharge verifies terminal items do not compete with each other.
//
// Example: one gap's released allowance admits the next gap and then the final service error.
func TestTerminalMetadataUsesOneSharedCharge(t *testing.T) {
	terminal := &pb.Event{Payload: &pb.Event_Error{Error: &pb.ServiceError{Message: strings.Repeat("x", 100)}}}
	budget := newSubscriptionBudget(proto.Size(terminal) + maximumSequenceCharge)
	queue, err := newSubscriptionQueueWithBudget(1, budget)
	require.NoError(t, err)
	defer queue.close()
	queue.recordDropLocked(pb.Channel_CHANNEL_2, 3)
	queue.recordDropLocked(pb.Channel_CHANNEL_1, 2)
	queue.finish(terminal, nil)
	for sequence := uint64(1); sequence <= 3; sequence++ {
		event, err := queue.next(t.Context())
		require.NoError(t, err)
		require.Equal(t, sequence, event.Sequence)
		require.Zero(t, budget.used.Load())
		if sequence == 3 {
			require.Same(t, terminal, event)
			continue
		}
		require.Equal(t, pb.Channel(sequence), event.GetWaveformGap().Channel)
	}
	_, err = queue.next(t.Context())
	require.ErrorIs(t, err, io.EOF)
}
