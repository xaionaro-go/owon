// requireNewServer constructs a valid test service or stops the current test.
//
// Example: gRPC harness setup registers its returned server implementation.
func requireNewServer(
	t *testing.T,
	instrument *owoncontrol.Controller,
) *Server {
	t.Helper()
	server, err := NewServer(instrument)
	require.NoError(t, err)

	return server
}

// TestServerBoundsActiveRPCAdmission verifies excess handlers fail before USB admission.
//
// Example: a second unary call receives ResourceExhausted while the first slot is held.
func TestServerBoundsActiveRPCAdmission(t *testing.T) {
	t.Parallel()

	server := requireNewServer(t, newTestInstrument(t, &scriptedBackend{}))
	server, err := NewServerWithConfig(server.instrument, ServerConfig{MaxActiveRPCs: 1, MaxActiveSubscriptions: 1})
	require.NoError(t, err)
	require.NoError(t, server.acquireRPC())
	require.Equal(t, codes.ResourceExhausted, status.Code(server.acquireRPC()))
	server.releaseRPC()
	require.NoError(t, server.acquireRPC())
	server.releaseRPC()
	_, err = NewServerWithConfig(server.instrument, ServerConfig{MaxActiveRPCs: maximumActiveRPCsCapacity + 1})
	requireErrorType[*ErrInvalidConfig](t, err)
}

