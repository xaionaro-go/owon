// TestRPCErrorMapsStableCategories verifies public status semantics for every error class.
//
// Example: malformed device replies map to DataLoss while queue exhaustion maps to ResourceExhausted.
func TestRPCErrorMapsStableCategories(t *testing.T) {
	t.Parallel()

	cases := []struct {
		Name string
		Err  error
		Code codes.Code
	}{
		{Name: "canceled", Err: context.Canceled, Code: codes.Canceled},
		{Name: "deadline", Err: context.DeadlineExceeded, Code: codes.DeadlineExceeded},
		{Name: "invalid", Err: new(owonmodel.ErrInvalidRequest), Code: codes.InvalidArgument},
		{Name: "unsupported", Err: new(owonscpi.ErrUnsupportedControl), Code: codes.Unimplemented},
		{Name: "malformed", Err: new(owonprotocol.ErrMalformedResponse), Code: codes.DataLoss},
		{Name: "surplus", Err: new(owonprotocol.ErrSurplusResponse), Code: codes.DataLoss},
		{Name: "backpressure", Err: new(ErrCriticalBackpressure), Code: codes.ResourceExhausted},
		{Name: "device", Err: errors.New("USB disconnected"), Code: codes.Unavailable},
		{Name: "preserve stream status", Err: status.Error(codes.PermissionDenied, "send failed"), Code: codes.PermissionDenied},
	}
	for _, testCase := range cases {
		t.Run(testCase.Name,
			// verifyStatusMapping checks one source error's stable public code.
			//
			// Example: the malformed case must remain DataLoss.
			func(t *testing.T) {
				require.Equal(t, testCase.Code, status.Code(rpcError("test", testCase.Err)))
			})
	}
}

