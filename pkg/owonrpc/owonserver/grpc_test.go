// grpcTestHarness owns the in-memory listener, server, connection, and terminal result.
//
// Example: TestClientServerIdentityPath registers its cleanup methods with testing.T.
type grpcTestHarness struct {
	test       *testing.T
	server     *grpc.Server
	listener   *bufconn.Listener
	connection *grpc.ClientConn
	errors     chan error
}

// cancellationBackend blocks one command until its RPC context is canceled.
//
// Example: a generated GetDeviceInfo call reaches USB simulation before cancellation.
type cancellationBackend struct {
	Entered  chan owonprotocol.Command
	Commands chan owonprotocol.Command
}

// Exchange reports the command, waits for cancellation, and returns its cause.
//
// Example: canceling the unary RPC returns context.Canceled from the backend boundary.
func (backend *cancellationBackend) Exchange(
	ctx context.Context,
	command owonprotocol.Command,
) ([]byte, error) {
	backend.Entered <- command
	<-ctx.Done()
	backend.Commands <- command

	return nil, ctx.Err()
}

