// serve runs the in-memory gRPC accept loop and publishes its terminal result.
//
// Example: observability.Go invokes it while the test performs RPCs.
func (harness *grpcTestHarness) serve(_ context.Context) {
	harness.errors <- harness.server.Serve(harness.listener)
}

// stop stops the test server, closes its listener, and verifies Serve returned cleanly.
//
// Example: testing.Cleanup invokes it after closing the client connection.
func (harness *grpcTestHarness) stop() {
	harness.server.Stop()
	require.NoError(harness.test, harness.listener.Close())
	require.NoError(harness.test, <-harness.errors)
}

// dial connects a gRPC client to the in-memory listener.
//
// Example: grpc.NewClient uses it as a context dialer for the passthrough target.
func (harness *grpcTestHarness) dial(
	ctx context.Context,
	_ string,
) (net.Conn, error) {
	return harness.listener.DialContext(ctx)
}

// closeConnection closes the test's client connection.
//
// Example: testing.Cleanup verifies the connection releases cleanly.
func (harness *grpcTestHarness) closeConnection() {
	require.NoError(harness.test, harness.connection.Close())
}

// TestClientServerIdentityPath verifies the built client reaches the actual
// gRPC server and decodes the instrument identity.
//
// Example: GetDeviceInfo crosses protobuf serialization over bufconn.
func TestClientServerIdentityPath(t *testing.T) {
	t.Parallel()

	backend := &scriptedBackend{Responses: map[string][]byte{
		"*IDN?": []byte("OWON,HDS2202S,25061855,V2.6.0"),
	}}
	transport, err := owonsession.New(backend, owonsession.Config{ExpectedSerial: "25061855"})
	require.NoError(t, err)
	instrument, err := owoncontrol.New(transport, owonmodel.DeviceIdentity{})
	require.NoError(t, err)
	listener := bufconn.Listen(1 << 20)
	grpcServer := grpc.NewServer(GRPCServerOptions()...)
	pb.RegisterOwonServiceServer(grpcServer, requireNewServer(t, instrument))
	harness := &grpcTestHarness{
		test:     t,
		server:   grpcServer,
		listener: listener,
		errors:   make(chan error, 1),
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	observability.Go(ctx, harness.serve)
	t.Cleanup(harness.stop)
	connection, err := grpc.NewClient(
		"passthrough:///owon-test",
		grpc.WithContextDialer(harness.dial),
		grpc.WithTransportCredentials(insecure.NewCredentials()),
		grpc.WithDefaultCallOptions(
			grpc.MaxCallRecvMsgSize(owonrpc.MaximumGRPCMessageBytes),
			grpc.MaxCallSendMsgSize(owonrpc.MaximumGRPCMessageBytes),
		),
	)
	require.NoError(t, err)
	harness.connection = connection
	t.Cleanup(harness.closeConnection)
	client, err := owonclient.NewClient(connection)
	require.NoError(t, err)

	info, err := client.DeviceInfo(ctx)
	require.NoError(t, err)
	require.Equal(t, "HDS2202S", info.Model)
	require.Equal(t, "25061855", info.Serial)
	display := false
	_, err = client.SetChannel(ctx, &pb.SetChannelRequest{Channel: pb.Channel_CHANNEL_2, Display: &display})
	require.NoError(t, err)
	require.Equal(t, []string{"*IDN?", ":CH2:DISPLAY OFF"}, backend.Commands)
}

// TestGRPCMessageLimitsPermitWaveformsAndRejectOversize verifies the shared wire budget.
//
// Example: five MiB crosses bufconn while a message larger than thirty-two MiB is rejected.
func TestGRPCMessageLimitsPermitWaveformsAndRejectOversize(t *testing.T) {
	t.Parallel()

	backend := &scriptedBackend{Responses: map[string][]byte{"BIG?": make([]byte, 5<<20)}}
	transport, err := owonsession.New(backend, owonsession.Config{ExpectedSerial: "25061855"})
	require.NoError(t, err)
	instrument, err := owoncontrol.New(transport, owonmodel.DeviceIdentity{})
	require.NoError(t, err)
	listener := bufconn.Listen(owonrpc.MaximumGRPCMessageBytes + 1)
	grpcServer := grpc.NewServer(GRPCServerOptions()...)
	pb.RegisterOwonServiceServer(grpcServer, requireNewServer(t, instrument))
	harness := &grpcTestHarness{test: t, server: grpcServer, listener: listener, errors: make(chan error, 1)}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	observability.Go(ctx, harness.serve)
	t.Cleanup(harness.stop)
	dialOptions := owonclient.GRPCClientDialOptions()
	dialOptions = append(dialOptions, grpc.WithContextDialer(harness.dial), grpc.WithTransportCredentials(insecure.NewCredentials()))
	connection, err := grpc.NewClient("passthrough:///owon-size-test", dialOptions...)
	require.NoError(t, err)
	harness.connection = connection
	t.Cleanup(harness.closeConnection)
	client, err := owonclient.NewClient(connection)
	require.NoError(t, err)

	response, err := client.Execute(ctx, &pb.ExecuteRequest{Command: "BIG?", ResponseMode: pb.ResponseMode_RESPONSE_MODE_OWON_LENGTH_PREFIXED})
	require.NoError(t, err)
	require.Len(t, response, 5<<20)
	backend.Responses["TOO_BIG?"] = make([]byte, owonrpc.MaximumGRPCMessageBytes+1)
	_, err = client.Execute(ctx, &pb.ExecuteRequest{Command: "TOO_BIG?", ResponseMode: pb.ResponseMode_RESPONSE_MODE_OWON_LENGTH_PREFIXED})
	require.Equal(t, codes.ResourceExhausted, status.Code(err))

	oversizedConnection, err := grpc.NewClient(
		"passthrough:///owon-inbound-size-test",
		grpc.WithContextDialer(harness.dial),
		grpc.WithTransportCredentials(insecure.NewCredentials()),
		grpc.WithDefaultCallOptions(
			grpc.MaxCallSendMsgSize(owonrpc.MaximumGRPCMessageBytes+(2<<20)),
			grpc.MaxCallRecvMsgSize(owonrpc.MaximumGRPCMessageBytes),
		),
	)
	require.NoError(t, err)
	oversizedClient := pb.NewOwonServiceClient(oversizedConnection)
	commandCount := len(backend.Commands)
	_, err = oversizedClient.Execute(ctx, &pb.ExecuteRequest{
		Command:      string(make([]byte, owonrpc.MaximumGRPCMessageBytes+1)),
		ResponseMode: pb.ResponseMode_RESPONSE_MODE_ASCII_LINE,
	})
	require.Equal(t, codes.ResourceExhausted, status.Code(err))
	require.Len(t, backend.Commands, commandCount)
	require.NoError(t, oversizedConnection.Close())
}

