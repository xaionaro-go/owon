// TestGeneratedClientSubscribeStreamsFIFOAndReleasesSlot verifies the real streaming path.
//
// Example: state, waveform, terminal error, and a later subscriber cross bufconn in FIFO order.
func TestGeneratedClientSubscribeStreamsFIFOAndReleasesSlot(t *testing.T) {
	t.Parallel()

	backend := &scriptedBackend{
		Responses: map[string][]byte{
			"*IDN?":                   []byte("OWON,HDS2202S,25061855,V2.6.0"),
			":DATA:WAVE:SCREEN:HEAD?": []byte(`{}`),
			":DATA:WAVE:SCREEN:CH1?":  {1, 2, 3},
		},
		ExchangeErrors: []error{nil, nil, nil, errors.New("USB disconnected")},
	}
	instrument := newTestInstrument(t, backend)
	service, err := NewServerWithConfig(instrument, ServerConfig{MaxActiveSubscriptions: 1})
	require.NoError(t, err)
	listener := bufconn.Listen(1 << 20)
	grpcServer := grpc.NewServer(GRPCServerOptions()...)
	pb.RegisterOwonServiceServer(grpcServer, service)
	harness := &grpcTestHarness{test: t, server: grpcServer, listener: listener, errors: make(chan error, 1)}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	observability.Go(ctx, harness.serve)
	t.Cleanup(harness.stop)
	dialOptions := owonclient.GRPCClientDialOptions()
	dialOptions = append(dialOptions, grpc.WithContextDialer(harness.dial), grpc.WithTransportCredentials(insecure.NewCredentials()))
	connection, err := grpc.NewClient("passthrough:///owon-subscribe-test", dialOptions...)
	require.NoError(t, err)
	harness.connection = connection
	t.Cleanup(harness.closeConnection)
	client, err := owonclient.NewClient(connection)
	require.NoError(t, err)

	stream, err := client.Subscribe(ctx, &pb.SubscribeRequest{
		Interval: durationpb.New(owonrpc.MinimumSubscriptionInterval), WaveformChannels: []pb.Channel{pb.Channel_CHANNEL_1},
	})
	require.NoError(t, err)
	state, err := stream.Recv()
	require.NoError(t, err)
	require.NotNil(t, state.GetState())
	require.Equal(t, uint64(1), state.Sequence)
	waveform, err := stream.Recv()
	require.NoError(t, err)
	require.NotNil(t, waveform.GetWaveform())
	require.Equal(t, uint64(2), waveform.Sequence)
	require.Equal(t, uint64(1), waveform.GetWaveform().Sequence)
	terminal, err := stream.Recv()
	require.NoError(t, err)
	require.Equal(t, uint64(3), terminal.Sequence)
	require.Equal(t, pb.ServiceErrorCategory_SERVICE_ERROR_CATEGORY_DEVICE_UNAVAILABLE, terminal.GetError().Category)
	_, err = stream.Recv()
	require.Equal(t, codes.Unavailable, status.Code(err))

	secondCtx, secondCancel := context.WithCancel(ctx)
	// Keep the next poll far away so cancellation cannot race a second queued state event.
	//
	// Example: this assertion tests slot release and cancellation, not ticker scheduling.
	second, err := client.Subscribe(secondCtx, &pb.SubscribeRequest{Interval: durationpb.New(time.Hour)})
	require.NoError(t, err)
	secondState, err := second.Recv()
	require.NoError(t, err)
	require.NotNil(t, secondState.GetState())
	secondCancel()
	_, err = second.Recv()
	require.Equal(t, codes.Canceled, status.Code(err))
}

