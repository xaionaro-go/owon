// TestSubscriptionSchedulingDoesNotSpendDeviceBudget keeps observable poll waiting outside the I/O timer.
//
// Example: a poll admitted after three operation budgets still receives a complete exchange budget.
func TestSubscriptionSchedulingDoesNotSpendDeviceBudget(t *testing.T) {
	synctest.Test(t,
		// verifyScheduledBudget consumes the first work window before entering the real producer poll.
		//
		// Example: scheduling delays do not become device-unavailable terminal events.
		func(t *testing.T) {
			backend := new(deadlineBackend)
			transport, err := owonsession.New(backend, owonsession.Config{ExpectedSerial: "serial", OperationTimeout: time.Second})
			require.NoError(t, err)
			instrument, err := owoncontrol.New(transport, owonmodel.DeviceIdentity{})
			require.NoError(t, err)
			scheduler, err := newSubscriptionPollScheduler(1, 3*time.Second)
			require.NoError(t, err)
			require.NoError(t, scheduler.acquire(context.Background(), 1))
			queue, err := newSubscriptionQueue(4)
			require.NoError(t, err)
			defer queue.close()
			producer := &subscriptionProducer{instrument: instrument, request: &pb.SubscribeRequest{}, queue: queue, pollScheduler: scheduler, pollWeight: 1}
			start := time.Now()
			require.NoError(t, producer.poll(context.Background()))
			require.Equal(t, 3*time.Second, time.Since(start))
			require.Equal(t, start.Add(4*time.Second), backend.Deadline)
			require.Equal(t, 1, backend.Calls)
			_, err = transport.Execute(context.Background(), owonprotocol.Command{Text: "*IDN?", ResponseMode: owonprotocol.ResponseModeASCII})
			require.NoError(t, err)
			require.Zero(t, backend.Recoveries, "successful polling must leave the transport healthy")
		})
}

// deadlineBackend records the actual I/O deadline and can wait for its expiry.
//
// Example: missing deadlines return immediately so baseline regressions cannot hang.
type deadlineBackend struct {
	Deadline         time.Time
	RecoveryDeadline time.Time
	Wait             bool
	RecoveryWait     bool
	Calls            int
	Recoveries       int
}

// Exchange observes the complete command budget and returns cancellation only after entry.
//
// Example: a default background caller receives a finite deadline at the backend boundary.
func (backend *deadlineBackend) Exchange(
	ctx context.Context,
	_ owonprotocol.Command,
) ([]byte, error) {
	backend.Calls++
	deadline, exists := ctx.Deadline()
	backend.Deadline = deadline
	if !exists {
		return nil, errors.New("exchange has no device deadline")
	}
	if backend.Wait {
		<-ctx.Done()
		return nil, ctx.Err()
	}
	return []byte("OWON,HDS2202S,serial,1.0"), nil
}

// ReopenAndValidate observes the independent recovery budget.
//
// Example: a failed recovery leaves the pending command unissued.
func (backend *deadlineBackend) ReopenAndValidate(
	ctx context.Context,
	_ owonmodel.SerialNumber,
) error {
	backend.Recoveries++
	deadline, exists := ctx.Deadline()
	backend.RecoveryDeadline = deadline
	if !exists {
		return errors.New("recovery has no device deadline")
	}
	if backend.RecoveryWait {
		<-ctx.Done()
		return ctx.Err()
	}
	return nil
}

// Close owns no external resources for this deterministic boundary fixture.
//
// Example: a test can close the transport after every admitted call has returned.
func (*deadlineBackend) Close(context.Context) error { return nil }
