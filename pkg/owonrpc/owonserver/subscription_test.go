// TestSubscriptionQueueCoalescesState verifies only the freshest unsent state is retained.
//
// Example: a slow client receives only the latest state as publication sequence one.
func TestSubscriptionQueueCoalescesState(t *testing.T) {
	t.Parallel()

	queue, err := newSubscriptionQueue(1)
	require.NoError(t, err)
	require.NoError(t, queue.enqueueState(&pb.Event{Payload: &pb.Event_State{State: new(pb.StateSnapshot)}}))
	require.NoError(t, queue.enqueueState(&pb.Event{Payload: &pb.Event_State{State: new(pb.StateSnapshot)}}))

	event, err := queue.next(context.Background())
	require.NoError(t, err)
	require.Equal(t, uint64(1), event.Sequence)
}

