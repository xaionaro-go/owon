// TestSubscribeDoesNotConsumeUnaryRPCAdmission verifies subscriptions have independent admission.
//
// Example: a held MaxActiveRPCs slot does not prevent a valid stream from starting and canceling.
func TestSubscribeDoesNotConsumeUnaryRPCAdmission(t *testing.T) {
	t.Parallel()

	backend := &scriptedBackend{Responses: map[string][]byte{
		"*IDN?": []byte("OWON,HDS2202S,25061855,V2.6.0"),
	}}
	server, err := NewServerWithConfig(
		newTestInstrument(t, backend),
		ServerConfig{MaxActiveRPCs: 1, MaxActiveSubscriptions: 1},
	)
	require.NoError(t, err)
	require.NoError(t, server.acquireRPC())
	defer server.releaseRPC()

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	client := newControlClientForServer(t, server)
	stream, err := client.Subscribe(ctx, &pb.SubscribeRequest{})
	require.NoError(t, err)
	event, err := stream.Recv()
	require.NoError(t, err)
	require.NotNil(t, event.GetState())
	cancel()
	_, err = stream.Recv()
	require.Equal(t, codes.Canceled, status.Code(err))
}

// TestSubscribeWaitsForProducerAfterSendError verifies child cancellation and producer join ordering.
//
// Example: a failed stream send cancels a blocked waveform query before Subscribe releases its slot.
func TestSubscribeWaitsForProducerAfterSendError(t *testing.T) {
	t.Parallel()

	backend := newSubscriptionCancellationBackend()
	server, err := NewServerWithConfig(
		newTestInstrument(t, backend),
		ServerConfig{MaxActiveSubscriptions: 1},
	)
	require.NoError(t, err)
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	result := make(chan error, 1)
	failure := subscriptionSendFailure{WaitForBackend: backend.headerEntered, Cause: errors.New("send failed"), Result: result}
	client := newControlClientForServer(t, server, grpc.StreamInterceptor(failure.intercept))
	stream, err := client.Subscribe(ctx, &pb.SubscribeRequest{WaveformChannels: []pb.Channel{pb.Channel_CHANNEL_1}})
	require.NoError(t, err)

	<-backend.cancelObserved
	select {
	case err := <-result:
		require.FailNow(t, "Subscribe returned before the blocked producer completed", err)
	default:
	}
	close(backend.releaseAfterCancel)
	require.ErrorContains(t, <-result, "send failed")
	_, err = stream.Recv()
	require.ErrorContains(t, err, "send failed")
}

// subscriptionCancellationBackend blocks one waveform header until its child context is canceled.
//
// Example: a send failure can be staged while the producer remains inside backend I/O.
type subscriptionCancellationBackend struct {
	headerEntered      chan struct{}
	cancelObserved     chan struct{}
	releaseAfterCancel chan struct{}
	headerOnce         sync.Once
	cancelOnce         sync.Once
}

// newSubscriptionCancellationBackend constructs a channel-controlled subscription backend.
//
// Example: tests release the backend only after observing producer cancellation.
func newSubscriptionCancellationBackend() *subscriptionCancellationBackend {
	return &subscriptionCancellationBackend{
		headerEntered:      make(chan struct{}),
		cancelObserved:     make(chan struct{}),
		releaseAfterCancel: make(chan struct{}),
	}
}

// Exchange returns identity and blocks the waveform header until cancellation.
//
// Example: the first state event can reach Send while the next producer operation remains blocked.
func (backend *subscriptionCancellationBackend) Exchange(
	ctx context.Context,
	command owonprotocol.Command,
) ([]byte, error) {
	switch command.Text {
	case "*IDN?":
		return []byte("OWON,HDS2202S,25061855,V2.6.0"), nil
	case ":DATA:WAVE:SCREEN:HEAD?":
		backend.headerOnce.Do(
			// signalHeaderEntered publishes the exact blocking backend boundary.
			//
			// Example: the send-failure fixture waits until a waveform read is active.
			func() {
				close(backend.headerEntered)
			})
		<-ctx.Done()
		backend.cancelOnce.Do(
			// signalCancellation publishes that the producer saw its child context.
			//
			// Example: the test releases cleanup only after cancellation reaches the backend.
			func() {
				close(backend.cancelObserved)
			})
		<-backend.releaseAfterCancel
		return nil, ctx.Err()
	default:
		return []byte(`{"CHANNEL":[]}`), nil
	}
}

// ReopenAndValidate satisfies Backend without reopening a staged subscription session.
