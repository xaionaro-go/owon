// TestSubscriptionQueueReportsWaveformDrops verifies bounded overflow becomes an explicit gap.
//
// Example: dropping sequence two produces one gap before sequence three.
func TestSubscriptionQueueReportsWaveformDrops(t *testing.T) {
	t.Parallel()

	queue, err := newSubscriptionQueue(1)
	require.NoError(t, err)
	channel := pb.Channel_CHANNEL_1
	require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: channel, Sequence: 1}}}))
	require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: channel, Sequence: 2}}}))
	first, err := queue.next(context.Background())
	require.NoError(t, err)
	require.Equal(t, uint64(1), first.Sequence)
	require.NoError(t, queue.enqueueWaveform(&pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{Channel: channel, Sequence: 3}}}))
	gap, err := queue.next(context.Background())
	require.NoError(t, err)
	require.Equal(t, uint64(2), gap.GetWaveformGap().FirstMissingSequence)
	require.Equal(t, uint64(2), gap.GetWaveformGap().LastMissingSequence)
	require.Equal(t, uint64(1), gap.GetWaveformGap().MissingCount)
	third, err := queue.next(context.Background())
	require.NoError(t, err)
	require.Equal(t, uint64(3), third.Sequence)
}

// TestSubscriptionClassifiesNonRetryableErrors verifies caller defects are not device outages.
