// TestSubscriptionQueuesShareAndReleaseServerBudget verifies cross-stream accounting.
//
// Example: dequeueing from one stream allows another stream to publish the same charge.
func TestSubscriptionQueuesShareAndReleaseServerBudget(t *testing.T) {
	t.Parallel()

	event := &pb.Event{Payload: &pb.Event_Waveform{Waveform: &pb.Waveform{
		Channel: pb.Channel_CHANNEL_1, Sequence: 1, Data: []byte{1},
	}}}
	charge := proto.Size(event) + maximumSequenceCharge
	budget := newSubscriptionBudget(charge)
	first, err := newSubscriptionQueueWithBudget(1, budget)
	require.NoError(t, err)
	second, err := newSubscriptionQueueWithBudget(1, budget)
	require.NoError(t, err)
	require.NoError(t, first.enqueueWaveform(event))
	requireErrorType[*ErrSubscriptionResourceExhausted](t, second.enqueueWaveform(event))
	_, err = first.next(context.Background())
	require.NoError(t, err)
	require.NoError(t, second.enqueueWaveform(event))
	second.close()
}

