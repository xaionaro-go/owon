// subscriptionSendFailure injects one send error while retaining real gRPC stream ownership.
//
// Example: the interceptor reports when Subscribe has finished joining its canceled producer.
type subscriptionSendFailure struct {
	WaitForBackend <-chan struct{}
	Cause          error
	Result         chan<- error
}

// intercept delegates to the generated handler with a stream that fails at the staged backend boundary.
//
// Example: the real stream supplies cancellation without storing a context in test fixtures.
func (failure subscriptionSendFailure) intercept(
	service any,
	stream grpc.ServerStream,
	_ *grpc.StreamServerInfo,
	handler grpc.StreamHandler,
) error {
	err := handler(service, &subscriptionFailingSend{ServerStream: stream, Failure: failure})
	failure.Result <- err
	return err
}

// subscriptionFailingSend replaces only outbound messages on a real server stream.
//
// Example: receiving the request and exposing its context still use the native gRPC stream.
type subscriptionFailingSend struct {
	grpc.ServerStream
	Failure subscriptionSendFailure
}

// SendMsg waits for the blocked backend query before returning the selected error.
//
// Example: the failure must cancel and join that query before the handler returns.
func (stream *subscriptionFailingSend) SendMsg(any) error {
	<-stream.Failure.WaitForBackend
	return stream.Failure.Cause
}

// scriptedBackend records transport activity and returns deterministic results.
//
// Example: tests configure one timeout followed by one successful exchange.
type scriptedBackend struct {
	Commands       []string
	ExchangeErrors []error
	ReopenCalls    int
	ReopenedSerial owonmodel.SerialNumber
	ReopenError    error
	Responses      map[string][]byte
	CloseErrors    []error
	CloseCalls     int
}

// Exchange records one command and returns its scripted response.
//
// Example: a configured first error models an ambiguous USB transfer.
func (backend *scriptedBackend) Exchange(
	_ context.Context,
	command owonprotocol.Command,
) ([]byte, error) {
	backend.Commands = append(backend.Commands, command.Text)
	if len(backend.ExchangeErrors) > 0 {
		err := backend.ExchangeErrors[0]
		backend.ExchangeErrors = backend.ExchangeErrors[1:]
		if err != nil {
			return nil, err
		}
	}
	return append([]byte(nil), backend.Responses[command.Text]...), nil
}

// ReopenAndValidate records the expected serial and returns its scripted error.
//
// Example: recovery tests assert that serial validation precedes a new write.
func (backend *scriptedBackend) ReopenAndValidate(
	_ context.Context,
	serial owonmodel.SerialNumber,
) error {
	backend.ReopenCalls++
	backend.ReopenedSerial = serial
	return backend.ReopenError
}

// Close satisfies Backend for deterministic tests.
//
// Example: no resources are owned by this in-memory backend.
func (backend *scriptedBackend) Close(_ context.Context) error {
	backend.CloseCalls++
	if len(backend.CloseErrors) == 0 {
		return nil
	}
	err := backend.CloseErrors[0]
	backend.CloseErrors = backend.CloseErrors[1:]

	return err
}
