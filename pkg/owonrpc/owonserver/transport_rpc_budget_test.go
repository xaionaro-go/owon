// silentRPCBackend models one silent command followed by a recovered instrument.
//
// Example: production Subscribe must terminate by its own device budget rather than client cancellation.
type silentRPCBackend struct {
	Calls      atomic.Int32
	Recoveries atomic.Int32
}

// Exchange blocks only the first exchange until its device deadline requests cancellation.
//
// Example: all later identity queries return actual parseable SCPI bytes.
func (backend *silentRPCBackend) Exchange(
	ctx context.Context,
	_ owonprotocol.Command,
) ([]byte, error) {
	if backend.Calls.Add(1) == 1 {
		<-ctx.Done()
		return nil, &owonprotocol.ErrMalformedResponse{Reason: "silent identity read", Cause: ctx.Err()}
	}
	return []byte("OWON,HDS2202S,serial,1.0"), nil
}

// ReopenAndValidate records the one recovery required after the failed exchange.
//
// Example: no recovery may occur before the silent operation has actually returned.
func (backend *silentRPCBackend) ReopenAndValidate(
	_ context.Context,
	serial owonmodel.SerialNumber,
) error {
	if serial != "serial" {
		return &owonmodel.ErrInvalidRequest{Reason: "unexpected recovery serial"}
	}
	backend.Recoveries.Add(1)
	return nil
}

// Close owns no external resources in this controlled endpoint fixture.
//
// Example: transport shutdown can join after all production RPC handlers stop.
func (*silentRPCBackend) Close(context.Context) error { return nil }

// TestTransportDeadlineThroughTCP verifies service metadata, terminal status and subsequent recovery.
//
// Example: DEVICE_UNAVAILABLE precedes DeadlineExceeded, then public identity and a new stream succeed.
func TestTransportDeadlineThroughTCP(t *testing.T) {
	backend := new(silentRPCBackend)
	transport, err := owonsession.New(backend, owonsession.Config{ExpectedSerial: "serial", OperationTimeout: 40 * time.Millisecond})
	require.NoError(t, err)
	t.Cleanup(
		// closeTransport joins ownership after all RPC and listener cleanup completes.
		//
		// Example: even an assertion failure leaves no retained device operation.
		func() { require.NoError(t, transport.Close()) })
	instrument, err := owoncontrol.New(transport, owonmodel.DeviceIdentity{})
	require.NoError(t, err)
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	server := grpc.NewServer(GRPCServerOptions()...)
	pb.RegisterOwonServiceServer(server, requireNewServer(t, instrument))
	done := make(chan error, 1)
	observability.Go(t.Context(),
		// serveTCP runs the real kernel listener until cleanup stops the production server.
		//
		// Example: protobuf status and event serialization use no fake RPC layer.
		func(context.Context) { done <- server.Serve(listener) })
	t.Cleanup(
		// stopTCP joins the real accept loop after canceling all active handlers.
		//
		// Example: the final healthy subscription cannot escape the test.
		func() {
			server.Stop()
			require.NoError(t, <-done)
		})
	connection, err := grpc.NewClient(listener.Addr().String(), grpc.WithTransportCredentials(insecure.NewCredentials()))
	require.NoError(t, err)
	t.Cleanup(
		// closeClient releases the public RPC connection before server shutdown.
		//
		// Example: no reconnect worker survives its test fixture.
		func() { require.NoError(t, connection.Close()) })
	client, err := owonclient.NewClient(connection)
	require.NoError(t, err)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	stream, err := client.Subscribe(ctx, &pb.SubscribeRequest{})
	require.NoError(t, err)
	event, err := stream.Recv()
	require.NoError(t, err)
	require.Equal(t, pb.ServiceErrorCategory_SERVICE_ERROR_CATEGORY_DEVICE_UNAVAILABLE, event.GetError().GetCategory())
	require.True(t, event.GetError().GetRetryable())
	require.Contains(t, event.GetError().GetMessage(), "deadline exceeded")
	_, err = stream.Recv()
	require.Equal(t, codes.DeadlineExceeded, status.Code(err))
	require.NoError(t, ctx.Err(), "outer watchdog must not rescue the silent operation")
	require.EqualValues(t, 1, backend.Calls.Load())
	info, err := client.DeviceInfo(ctx)
	require.NoError(t, err)
	require.Equal(t, "serial", info.Serial)
	require.EqualValues(t, 1, backend.Recoveries.Load())
	stream, err = client.Subscribe(ctx, &pb.SubscribeRequest{Interval: durationpb.New(200 * time.Millisecond)})
	require.NoError(t, err)
	for range 3 {
		event, err := stream.Recv()
		require.NoError(t, err)
		require.NotNil(t, event.GetState())
		require.Nil(t, event.GetError())
	}
	require.EqualValues(t, 1, backend.Recoveries.Load())
	t.Log("retryable DEVICE_UNAVAILABLE -> DeadlineExceeded; one recovery; identity and three healthy states across idle device budgets")
}
