// requireClientRequestBoundary checks nil requests and unavailable clients without issuing remote work.
//
// Example: a nil setter request returns client ErrInvalidInput while a nil client returns ErrUnavailable.
func requireClientRequestBoundary[Request any, Result any](
	t *testing.T,
	call func(
		context.Context,
		*Request,
	) (Result, error),
	missing func(
		context.Context,
		*Request,
	) (Result, error),
) {
	t.Helper()
	_, err := call(t.Context(), nil)
	requireErrorType[*owonclient.ErrInvalidInput](t, err)
	_, err = call(nil, new(Request))
	requireErrorType[*owonclient.ErrInvalidInput](t, err)
	_, err = missing(t.Context(), new(Request))
	requireErrorType[*owonclient.ErrUnavailable](t, err)
}

// TestClientRejectsUnavailableInputs verifies consistent local validation for all request-bearing methods.
//
// Example: validation fails before an absent connection could be dereferenced.
func TestClientRejectsUnavailableInputs(t *testing.T) {
	t.Parallel()
	backend := &scriptedBackend{}
	client := newControlClient(t, backend)
	var missing *owonclient.Client
	requireClientRequestBoundary(t, client.Execute, missing.Execute)
	requireClientRequestBoundary(t, client.State, missing.State)
	requireClientRequestBoundary(t, client.SetChannel, missing.SetChannel)
	requireClientRequestBoundary(t, client.SetAcquisition, missing.SetAcquisition)
	requireClientRequestBoundary(t, client.SetHorizontal, missing.SetHorizontal)
	requireClientRequestBoundary(t, client.SetTrigger, missing.SetTrigger)
	requireClientRequestBoundary(t, client.SetMeasurement, missing.SetMeasurement)
	requireClientRequestBoundary(t, client.SetGenerator, missing.SetGenerator)
	requireClientRequestBoundary(t, client.SetDMM, missing.SetDMM)
	requireClientRequestBoundary(t, client.Waveform, missing.Waveform)
	requireClientRequestBoundary(t, client.Subscribe, missing.Subscribe)
	for _, call := range []func(context.Context) (*pb.CommandResult, error){missing.Run, missing.Stop, missing.Single} {
		result, err := call(t.Context())
		requireErrorType[*owonclient.ErrUnavailable](t, err)
		require.Nil(t, result)
	}
	_, err := missing.DeviceInfo(t.Context())
	requireErrorType[*owonclient.ErrUnavailable](t, err)
	_, err = missing.DMMMeasurement(t.Context())
	requireErrorType[*owonclient.ErrUnavailable](t, err)
	require.Empty(t, backend.Commands)
}
