// newControlClient connects a typed public client to the real service over an in-memory transport.
//
// Example: control tests verify protobuf optional-field presence through the complete RPC stack.
func newControlClient(
	t *testing.T,
	backend owonsession.Backend,
) *owonclient.Client {
	t.Helper()
	return newControlClientForServer(t, requireNewServer(t, newTestInstrument(t, backend)))
}

// newControlClientForServer connects to a configured service with optional transport instrumentation.
//
// Example: subscription tests inject a send failure while retaining a real stream cancellation context.
func newControlClientForServer(
	t *testing.T,
	server *Server,
	options ...grpc.ServerOption,
) *owonclient.Client {
	t.Helper()
	options = append(GRPCServerOptions(), options...)
	harness := &grpcTestHarness{test: t, server: grpc.NewServer(options...), listener: bufconn.Listen(1 << 20), errors: make(chan error, 1)}
	pb.RegisterOwonServiceServer(harness.server, server)
	observability.Go(t.Context(), harness.serve)
	t.Cleanup(harness.stop)
	connection, err := grpc.NewClient("passthrough:///owon-controls", grpc.WithContextDialer(harness.dial), grpc.WithTransportCredentials(insecure.NewCredentials()))
	require.NoError(t, err)
	harness.connection = connection
	t.Cleanup(harness.closeConnection)
	client, err := owonclient.NewClient(connection)
	require.NoError(t, err)
	return client
}

// TestClientControlPaths verifies every typed mutation preserves false and zero and issues the expected commands.
//
// Example: offset zero and display false survive protobuf serialization and receive application timestamps.
func TestClientControlPaths(t *testing.T) {
	t.Parallel()
	backend := &scriptedBackend{}
	client := newControlClient(t, backend)
	ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
	defer cancel()
	disabled, zero := false, 0.0
	offset := int64(0)
	mode := pb.AcquisitionMode_ACQUISITION_MODE_PEAK_DETECT
	source := pb.TriggerSource_TRIGGER_SOURCE_CHANNEL_2
	coupling := pb.Coupling_COUPLING_AC
	slope := pb.TriggerSlope_TRIGGER_SLOPE_FALLING
	sweep := pb.TriggerSweep_TRIGGER_SWEEP_NORMAL
	result, err := client.SetChannel(ctx, &pb.SetChannelRequest{Channel: pb.Channel_CHANNEL_2, Display: &disabled, Coupling: &coupling})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	result, err = client.SetAcquisition(ctx, &pb.SetAcquisitionRequest{Mode: &mode})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	result, err = client.SetHorizontal(ctx, &pb.SetHorizontalRequest{OffsetDivisions: &offset})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	result, err = client.SetTrigger(ctx, &pb.SetTriggerRequest{Source: &source, Coupling: &coupling, Slope: &slope, Sweep: &sweep, LevelVolts: &zero})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	result, err = client.SetMeasurement(ctx, &pb.SetMeasurementRequest{Display: &disabled})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	result, err = client.SetGenerator(ctx, &pb.SetGeneratorRequest{Output: &disabled})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	result, err = client.SetDMM(ctx, &pb.SetDmmRequest{Relative: &disabled})
	require.NoError(t, err)
	require.NotNil(t, result.AppliedAt)
	for _, run := range []func(context.Context) (*pb.CommandResult, error){client.Run, client.Stop, client.Single} {
		result, err = run(ctx)
		require.NoError(t, err)
		require.NotNil(t, result.AppliedAt)
	}
	require.Equal(t, []string{":CH2:DISPLAY OFF", ":CH2:COUPLING AC", ":ACQUIRE:MODE PEAK", ":HORIZONTAL:OFFSET 0", ":TRIGGER:SINGLE:SOURCE CH2", ":TRIGGER:SINGLE:COUPLING AC", ":TRIGGER:SINGLE:EDGE FALL", ":TRIGGER:SINGLE:EDGE:LEVEL 0V", ":TRIGGER:SINGLE:SWEEP NORMAL", ":MEASUREMENT:DISPLAY OFF", ":CHANNEL OFF", ":DMM:REL OFF", ":RUN", ":STOP", ":SINGLE"}, backend.Commands)
}

// TestClientReadPaths verifies decoded readings, opaque waveform bytes, and metadata across public RPCs.
//
// Example: zero DMM and scope values remain readings while corrupt device tokens fail with DataLoss.
func TestClientReadPaths(t *testing.T) {
	t.Parallel()
	for _, raw := range []string{"0", "-1.25", "NaN", "+Inf", "invalid"} {
		backend := &scriptedBackend{Responses: map[string][]byte{"*IDN?": []byte("OWON,HDS2202S,25061855,V2.6.0"), ":DMM:MEAS?": []byte(raw + " V"), ":MEASUREMENT:CH1:FREQUENCY?": []byte(raw), ":DATA:WAVE:SCREEN:HEAD?": []byte(`{"SAMPLE":{"DATALEN":3}}`), ":DATA:WAVE:SCREEN:CH1?": {0, 128, 255}}}
		client := newControlClient(t, backend)
		ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
		defer cancel()
		measurement, dmmErr := client.DMMMeasurement(ctx)
		state, stateErr := client.State(ctx, &pb.GetStateRequest{Measurements: []*pb.MeasurementSelector{{Channel: pb.Channel_CHANNEL_1, Kind: pb.MeasurementKind_MEASUREMENT_KIND_FREQUENCY}}})
		switch raw {
		case "0", "-1.25":
			require.NoError(t, dmmErr)
			require.NoError(t, stateErr)
			want := map[string]float64{"0": 0, "-1.25": -1.25}[raw]
			require.Equal(t, want, measurement.Value)
			require.Nil(t, measurement.Function)
			require.Equal(t, "V", measurement.Unit)
			require.Equal(t, want, state.Measurements[0].Value)
		default:
			require.Nil(t, measurement)
			require.Nil(t, state)
			require.Equal(t, codes.DataLoss, status.Code(dmmErr), raw)
			require.Equal(t, codes.DataLoss, status.Code(stateErr), raw)
			stream, err := client.Subscribe(ctx, &pb.SubscribeRequest{Measurements: []*pb.MeasurementSelector{{Channel: pb.Channel_CHANNEL_1, Kind: pb.MeasurementKind_MEASUREMENT_KIND_FREQUENCY}}})
			require.NoError(t, err)
			event, err := stream.Recv()
			require.NoError(t, err)
			require.Equal(t, pb.ServiceErrorCategory_SERVICE_ERROR_CATEGORY_PROTOCOL, event.GetError().Category)
			require.True(t, event.GetError().Retryable)
			_, err = stream.Recv()
			require.Equal(t, codes.DataLoss, status.Code(err))
		}
		waveform, err := client.Waveform(ctx, &pb.GetWaveformRequest{Channel: pb.Channel_CHANNEL_1, Screen: true})
		require.NoError(t, err)
		require.Equal(t, []byte{0, 128, 255}, waveform.Data)
		require.Nil(t, waveform.Metadata.SampleCount)
	}
}

// TestClientStateIncludesTypedDMMRange verifies observed range readback crosses the complete RPC boundary.
//
// Example: a documented mV response is exposed as DMM_RANGE_MV without inventing a native hold state.
func TestClientStateIncludesTypedDMMRange(t *testing.T) {
	t.Parallel()

	backend := &scriptedBackend{Responses: map[string][]byte{
		"*IDN?":                   []byte("OWON,HDS2202S,25061855,V2.6.0"),
		":DATA:WAVE:SCREEN:HEAD?": []byte(`{"TIMEBASE":{"SCALE":"20us"},"SAMPLE":{"TYPE":"SAMPle"},"CHANNEL":[{"NAME":"CH1","DISPLAY":"ON","COUPLING":"DC","PROBE":"10X","SCALE":"1.00V"}],"Trig":{"Mode":"SINGLE","Type":"EDGE","Items":{"Channel":"CH1","Level":"1V","Edge":"RISE","Coupling":"DC","Sweep":"AUTO"}}}`),
		":DMM:RANGE?":             []byte("mV"),
	}}
	snapshot, err := newControlClient(t, backend).State(t.Context(), &pb.GetStateRequest{IncludeControls: true})
	require.NoError(t, err)
	require.NotNil(t, snapshot.GetDmm())
	require.Equal(t, pb.DmmRange_DMM_RANGE_MV, snapshot.GetDmm().GetRange())
	require.Equal(t, "mV", snapshot.GetDmm().GetObservedRangeToken())
	require.Equal(t, []string{"*IDN?", ":DATA:WAVE:SCREEN:HEAD?", ":DMM:RANGE?"}, backend.Commands)
}

