// GetWaveform returns raw waveform bytes and verified metadata.
//
// Example: sample bytes remain uninterpreted until device encoding is proven.
func (server *Server) GetWaveform(
	ctx context.Context,
	request *pb.GetWaveformRequest,
) (*pb.Waveform, error) {
	if err := server.acquireRPC(); err != nil {
		return nil, err
	}
	defer server.releaseRPC()
	instrument, instrumentErr := server.serviceInstrument()
	if instrumentErr != nil {
		return nil, instrumentErr
	}
	waveform, err := instrument.Waveform(ctx, owonrpc.WaveformRequestFromProto(request))
	if err != nil {
		return nil, rpcError("get waveform", err)
	}

	result := owonrpc.WaveformToProto(waveform)
	if err := validateWaveformWireSize(&pb.Event{Timestamp: result.CapturedAt, Payload: &pb.Event_Waveform{Waveform: result}}); err != nil {
		return nil, rpcError("get waveform", err)
	}
	return result, nil
}

// commandResult returns an application timestamp after a successful control mutation.
//
// Example: setters use this result after the final SCPI write succeeds.
func commandResult(now time.Time) *pb.CommandResult {
	return &pb.CommandResult{AppliedAt: timestamppb.New(now)}
}

// ErrInvalidInput identifies invalid RPC server input.
//
// Example: callers can distinguish local RPC failures through errors.As.
type ErrInvalidInput struct {
	Reason string
	Cause  error
}

// Error describes the local failure and retains useful cause text.
//
// Example: logging the error identifies the failed RPC boundary.
func (err *ErrInvalidInput) Error() string {
	if err == nil {
		return "invalid RPC server input"
	}
	detail := err.Reason
	if detail == "" {
		detail = "invalid RPC server input"
	}
	if err.Cause != nil {
		return fmt.Sprintf("%s: %v", detail, err.Cause)
	}
	return detail
}

// Unwrap exposes the originating failure.
//
// Example: errors.Is follows a preserved context cancellation cause.
func (err *ErrInvalidInput) Unwrap() error {
	if err == nil {
		return nil
	}
	return err.Cause
}

