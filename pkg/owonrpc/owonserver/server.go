const (
	// defaultMaximumActiveRPCs bounds concurrent unary handlers.
	//
	// Example: the sixty-fifth unary request fails fast instead of waiting behind USB admission forever.
	defaultMaximumActiveRPCs = 64
	// maximumActiveRPCsCapacity bounds configured RPC admission memory.
	//
	// Example: a typo such as one million handlers is rejected during startup.
	maximumActiveRPCsCapacity = 1024
	// DefaultMaximumActiveSubscriptions bounds concurrent polling streams when configuration is omitted.
	//
	// Example: the thirty-third default subscription receives ResourceExhausted.
	DefaultMaximumActiveSubscriptions = 32
	// MaximumActiveSubscriptions bounds configured concurrent stream admission.
	//
	// Example: daemon flags and service construction reject more than 1024 subscriptions.
	MaximumActiveSubscriptions = 1024
)

// ServerConfig controls server-wide resource concurrency.
//
// MaxActiveRPCs applies only to unary handlers; Subscribe uses MaxActiveSubscriptions
// and the shared queue budget for its lifetime. MaxSubscriptionPollWork is the weighted
// transport-command allowance per one-second window; zero selects the safe default. Each
// gRPC connection is also bounded by MaximumGRPCConcurrentStreams.
//
// Example: MaxActiveSubscriptions=8 and MaxSubscriptionPollWork=64 bound stream count and
// aggregate estimated poll commands independently.
type ServerConfig struct {
	MaxActiveRPCs           int
	MaxActiveSubscriptions  int
	MaxSubscriptionPollWork int
}

// Server implements the gRPC API over one typed instrument.
//
// Example: register the successfully constructed server with RegisterOwonServiceServer.
type Server struct {
	pb.UnimplementedOwonServiceServer
	instrument                Instrument
	rpcAdmission              chan struct{}
	subscriptions             chan struct{}
	subscriptionBudget        *subscriptionBudget
	subscriptionPollScheduler *subscriptionPollScheduler
}

// NewServer constructs a gRPC service for one instrument.
//
// Example: a daemon handles the constructor error before registering the service.
func NewServer(instrument Instrument) (*Server, error) {
	return NewServerWithConfig(instrument, ServerConfig{})
}

// NewServerWithConfig constructs a service with explicit resource limits.
//
// Example: tests configure one active subscription to exercise admission failure.
func NewServerWithConfig(
	instrument Instrument,
	config ServerConfig,
) (*Server, error) {
	if isNilInstrument(instrument) {
		return nil, &ErrInvalidConfig{Reason: "create OWON server: instrument is nil"}
	}
	if config.MaxActiveRPCs < 0 || config.MaxActiveSubscriptions < 0 || config.MaxSubscriptionPollWork < 0 {
		return nil, &ErrInvalidConfig{Reason: "server resource counts must not be negative"}
	}
	if config.MaxActiveSubscriptions == 0 {
		config.MaxActiveSubscriptions = DefaultMaximumActiveSubscriptions
	}
	if config.MaxActiveRPCs == 0 {
		config.MaxActiveRPCs = defaultMaximumActiveRPCs
	}
	if config.MaxSubscriptionPollWork == 0 {
		config.MaxSubscriptionPollWork = defaultMaximumSubscriptionPollWork
	}
	if config.MaxActiveRPCs > maximumActiveRPCsCapacity {
		return nil, fmt.Errorf("maximum active RPCs %d exceeds %d: %w", config.MaxActiveRPCs, maximumActiveRPCsCapacity, &ErrInvalidConfig{Reason: "maximum active RPC count exceeds the configured maximum"})
	}
	if config.MaxActiveSubscriptions > MaximumActiveSubscriptions {
		return nil, fmt.Errorf("maximum active subscriptions %d exceeds %d: %w", config.MaxActiveSubscriptions, MaximumActiveSubscriptions, &ErrInvalidConfig{Reason: "maximum active subscription count exceeds the configured maximum"})
	}
	if config.MaxSubscriptionPollWork > maximumSubscriptionPollWorkCapacity {
		return nil, fmt.Errorf("maximum subscription poll work %d exceeds %d: %w", config.MaxSubscriptionPollWork, maximumSubscriptionPollWorkCapacity, &ErrInvalidConfig{Reason: "maximum poll work exceeds the configured maximum"})
	}
	pollScheduler, err := newSubscriptionPollScheduler(config.MaxSubscriptionPollWork, subscriptionPollWorkWindow)
	if err != nil {
		return nil, fmt.Errorf("create subscription poll scheduler: %w", err)
	}

	return &Server{
		instrument:                instrument,
		rpcAdmission:              make(chan struct{}, config.MaxActiveRPCs),
		subscriptions:             make(chan struct{}, config.MaxActiveSubscriptions),
		subscriptionBudget:        newSubscriptionBudget(maximumServerSubscriptionBytes),
		subscriptionPollScheduler: pollScheduler,
	}, nil
}

// acquireRPC reserves one bounded handler slot without blocking.
//
// Example: excess clients receive ResourceExhausted before waiting on USB admission.
func (server *Server) acquireRPC() error {
	if server == nil || server.rpcAdmission == nil {
		return status.Error(codes.FailedPrecondition, "RPC admission is unavailable")
	}
	select {
	case server.rpcAdmission <- struct{}{}:
		return nil
	default:
		return status.Error(codes.ResourceExhausted, "maximum active RPCs reached")
	}
}

// releaseRPC returns one bounded unary-handler slot.
//
// Example: every unary method defers release after admission.
func (server *Server) releaseRPC() {
	if server == nil || server.rpcAdmission == nil {
		return
	}
	<-server.rpcAdmission
}

// acquireSubscription reserves one server-wide stream slot without blocking.
//
// Example: exhausted admission returns ResourceExhausted immediately.
func (server *Server) acquireSubscription() error {
	if server == nil || server.subscriptions == nil {
		return status.Error(codes.FailedPrecondition, "subscription admission is unavailable")
	}
	select {
	case server.subscriptions <- struct{}{}:
		return nil
	default:
		return status.Error(codes.ResourceExhausted, "maximum active subscriptions reached")
	}
}

// releaseSubscription returns one server-wide stream slot.
//
// Example: Subscribe defers it after successful admission.
func (server *Server) releaseSubscription() {
	<-server.subscriptions
}

// serviceInstrument returns the configured instrument or a stable gRPC precondition error.
//
// Example: direct method calls on a nil server cannot panic.
func (server *Server) serviceInstrument() (Instrument, error) {
	if server == nil || isNilInstrument(server.instrument) {
		return nil, status.Error(codes.FailedPrecondition, "instrument is unavailable")
	}

	return server.instrument, nil
}

// GetDeviceInfo returns the connected instrument's current SCPI identity.
//
// Example: clients can reject a daemon connected to an unexpected serial.
func (server *Server) GetDeviceInfo(
	ctx context.Context,
	_ *emptypb.Empty,
) (*pb.DeviceInfo, error) {
	if err := server.acquireRPC(); err != nil {
		return nil, err
	}
	defer server.releaseRPC()
	instrument, instrumentErr := server.serviceInstrument()
	if instrumentErr != nil {
		return nil, instrumentErr
	}
	info, err := instrument.DeviceInfo(ctx)
	if err != nil {
		return nil, rpcError("get device info", err)
	}

	return owonrpc.DeviceInfoToProto(info), nil
}

