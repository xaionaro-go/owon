// Execute performs one validated raw command with caller-selected response framing.
//
// Example: RESPONSE_MODE_ASCII_LINE safely carries an identity query.
func (server *Server) Execute(
	ctx context.Context,
	request *pb.ExecuteRequest,
) (*pb.ExecuteResponse, error) {
	if err := server.acquireRPC(); err != nil {
		return nil, err
	}
	defer server.releaseRPC()
	if request == nil {
		return nil, status.Error(codes.InvalidArgument, "request is required")
	}
	instrument, instrumentErr := server.serviceInstrument()
	if instrumentErr != nil {
		return nil, instrumentErr
	}
	command, err := owonrpc.CommandFromProto(request)
	if err != nil {
		return nil, status.Error(codes.InvalidArgument, err.Error())
	}
	response, err := instrument.Execute(ctx, command)
	if err != nil {
		var invalidCommand *owonprotocol.ErrInvalidCommand
		if errors.As(err, &invalidCommand) {
			return nil, status.Error(codes.InvalidArgument, err.Error())
		}
		return nil, rpcError("execute command", err)
	}

	return &pb.ExecuteResponse{Data: response}, nil
}

