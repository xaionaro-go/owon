package owonrpc

import (
	"testing"
	"time"

	"github.com/stretchr/testify/require"
	pb "github.com/xaionaro-go/owon/pkg/owonrpc/autogenerated"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/known/durationpb"
)

// TestSubscribeValidatorChecksIntervalAndCapacity verifies pure validation owns the entire domain.
//
// Example: malformed protobuf durations retain both caller-error classification and protobuf cause.
func TestSubscribeValidatorChecksIntervalAndCapacity(t *testing.T) {
	for _, request := range []*pb.SubscribeRequest{
		{Interval: durationpb.New(0)},
		{Interval: durationpb.New(-time.Second)},
		{Interval: durationpb.New(19 * time.Millisecond)},
		{Interval: &durationpb.Duration{Seconds: 1, Nanos: -1}},
		{Interval: &durationpb.Duration{Nanos: 1000000000}},
		{Interval: &durationpb.Duration{Seconds: 315576000001}},
		{QueueCapacity: 1025},
	} {
		before := proto.Clone(request)
		err := ValidateSubscribeRequest(request)
		requireErrorType[*ErrInvalidInput](t, err)
		require.True(t, proto.Equal(before, request))
		if request.Interval != nil && request.Interval.CheckValid() != nil {
			require.ErrorIs(t, err, proto.Error)
		}
	}
}
