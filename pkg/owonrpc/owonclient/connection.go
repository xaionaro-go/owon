package owonclient

import (
	"context"
	"errors"
	"fmt"

	"github.com/facebookincubator/go-belt"
	"github.com/facebookincubator/go-belt/tool/logger"
	"github.com/xaionaro-go/owon/pkg/owonrpc"
	pb "github.com/xaionaro-go/owon/pkg/owonrpc/autogenerated"
	"google.golang.org/grpc"
	"google.golang.org/grpc/credentials/insecure"
)

// ConnectionConfig describes endpoint and credential policy shared by RPC consumers.
//
// Example: CLI commands and the web bridge use the same remote TLS requirements.
type ConnectionConfig struct {
	Endpoint owonrpc.Endpoint
	TLS      owonrpc.ClientTLSConfig
}

// Validate rejects invalid endpoints and incomplete transport credential policy.
//
// Example: a remote TCP address requires all four mutual-TLS configuration values.
func (config ConnectionConfig) Validate() error {
	if _, err := config.Endpoint.Target(); err != nil {
		return err
	}
	required, err := config.Endpoint.RequiresTLS()
	if err != nil {
		return err
	}
	configured := config.TLS != (owonrpc.ClientTLSConfig{})
	if !required && configured {
		return &owonrpc.ErrTLSConfiguration{Reason: "client TLS settings are unsupported for local endpoints"}
	}
	if required {
		if config.TLS.CAFile == "" || config.TLS.CertificateFile == "" || config.TLS.PrivateKeyFile == "" || config.TLS.ServerName == "" {
			return &owonrpc.ErrTLSConfiguration{Reason: "client TLS requires CA, certificate, private key, and server name"}
		}
	}
	return nil
}

// DialOptions loads credentials and applies the service's common message bounds.
//
// Example: local Unix connections use insecure gRPC only when no TLS is configured.
func (config ConnectionConfig) DialOptions() ([]grpc.DialOption, error) {
	if err := config.Validate(); err != nil {
		return nil, err
	}
	credentials := insecure.NewCredentials()
	if config.TLS != (owonrpc.ClientTLSConfig{}) {
		loaded, err := owonrpc.LoadClientTLSCredentials(config.TLS)
		if err != nil {
			return nil, err
		}
		credentials = loaded
	}
	return append(GRPCClientDialOptions(), grpc.WithTransportCredentials(credentials)), nil
}

// Connection owns one lazy transport and exposes its typed operations.
// The client borrows that transport; Close remains the owner's responsibility.
//
// Example: one command defers Close and performs RPCs with its own deadline context.
type Connection struct {
	client    *Client
	transport *grpc.ClientConn
}

// NewConnection constructs a lazy transport without checking network readiness.
// Context is used only for local cancellation and logging; RPCs supply their own context.
//
// Example: configuring an unavailable daemon succeeds until the first RPC attempts I/O.
func NewConnection(
	ctx context.Context,
	config ConnectionConfig,
) (_connection *Connection, _err error) {
	if ctx == nil {
		return nil, &ErrInvalidInput{Reason: "create OWON connection: context is nil"}
	}
	logger.Tracef(ctx, "NewConnection")
	defer
	// traceConnection reports construction failure without retaining the context.
	//
	// Example: invalid credentials appear in the exit trace.
	func() { logger.Tracef(ctx, "/NewConnection: %v", _err) }()
	if err := ctx.Err(); err != nil {
		return nil, fmt.Errorf("create OWON connection: %w", err)
	}
	options, err := config.DialOptions()
	if err != nil {
		return nil, err
	}
	target, err := config.Endpoint.Target()
	if err != nil {
		return nil, err
	}
	transport, err := grpc.NewClient(target, options...)
	if err != nil {
		return nil, fmt.Errorf("create OWON transport: %w", err)
	}
	client, err := NewClient(transport)
	if err != nil {
		return nil, errors.Join(err, transport.Close())
	}
	logger.Debugf(belt.WithField(ctx, "endpoint", target), "created lazy RPC connection")
	return &Connection{client: client, transport: transport}, nil
}

// Client returns the typed operations bound to this owner's transport.
//
// Example: callers perform DeviceInfo without being able to rebind the owning connection.
func (connection *Connection) Client() *Client {
	if connection == nil {
		return nil
	}
	return connection.client
}

// RPCClient exposes generated operations needed by the HTTP bridge without transport ownership.
//
// Example: NewHandler receives this service client and cannot close the underlying connection.
func (connection *Connection) RPCClient() pb.OwonServiceClient {
	if connection == nil || connection.transport == nil {
		return nil
	}
	return pb.NewOwonServiceClient(connection.transport)
}

// Close releases the owned transport and preserves its closure error.
//
// Example: callers join a command failure with any independent close failure.
func (connection *Connection) Close() error {
	if connection == nil || connection.transport == nil {
		return &ErrUnavailable{Operation: "close OWON connection", Resource: "transport", Reason: "is unavailable"}
	}
	if err := connection.transport.Close(); err != nil {
		return fmt.Errorf("close OWON connection: %w", err)
	}
	return nil
}
