// Client is the reusable typed Go client for an OWON gRPC service.
//
// Example: construct it from a grpc.ClientConn and call DeviceInfo.
type Client struct {
	rpc pb.OwonServiceClient
}

// NewClient constructs a typed client over an existing gRPC connection.
//
// Example: callers retain ownership of the connection and close it during shutdown.
func NewClient(connection grpc.ClientConnInterface) (*Client, error) {
	if connection == nil || isNilClientConnection(connection) {
		return nil, &ErrInvalidConfig{Reason: "create OWON client: gRPC connection is nil"}
	}

	return &Client{rpc: pb.NewOwonServiceClient(connection)}, nil
}

// isNilClientConnection detects a typed nil connection interface before client construction.
//
// Example: a nil *grpc.ClientConn cannot be retained as an unusable generated client.
func isNilClientConnection(connection grpc.ClientConnInterface) bool {
	value := reflect.ValueOf(connection)
	switch value.Kind() {
	case reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice:
		return value.IsNil()
	default:
		return false
	}
}

// serviceClient returns the configured generated client or a deterministic local error.
//
// Example: every public method uses it so nil clients and nil contexts cannot panic.
func (client *Client) serviceClient(ctx context.Context) (pb.OwonServiceClient, error) {
	if client == nil || client.rpc == nil {
		return nil, &ErrUnavailable{Operation: "use OWON gRPC client", Resource: "client", Reason: "is unavailable"}
	}
	if ctx == nil {
		return nil, &ErrInvalidInput{Reason: "use OWON gRPC client: context is nil"}
	}

	return client.rpc, nil
}

