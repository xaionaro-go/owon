// ErrUnavailable identifies RPC client unavailable.
//
// Example: callers can distinguish local RPC failures through errors.As.
type ErrUnavailable struct {
	Operation string
	Resource  string
	Reason    string
	Cause     error
}

// Error describes the local failure and retains useful cause text.
//
// Example: logging the error identifies the failed RPC boundary.
func (err *ErrUnavailable) Error() string {
	if err == nil {
		return "RPC client unavailable"
	}
	detail := err.Reason
	if err.Operation != "" || err.Resource != "" {
		detail = fmt.Sprintf("%s: %s %s", err.Operation, err.Resource, detail)
	}
	if detail == "" {
		detail = "RPC client unavailable"
	}
	if err.Cause != nil {
		return fmt.Sprintf("%s: %v", detail, err.Cause)
	}
	return detail
}

