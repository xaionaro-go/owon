package owonrpc

import (
	"slices"

	"github.com/xaionaro-go/owon/pkg/owonmodel"
	pb "github.com/xaionaro-go/owon/pkg/owonrpc/autogenerated"
	"google.golang.org/protobuf/types/known/timestamppb"
)

// StateRequestFromProto converts wire fields to native values with independent mutable ownership.
//
// Example: requested measurement selectors are copied without changing the IncludeControls flag.
func StateRequestFromProto(value *pb.GetStateRequest) *owonmodel.StateRequest {
	if value == nil {
		return nil
	}
	result := &owonmodel.StateRequest{
		Measurements:        nil,
		IncludeScreenHeader: value.IncludeScreenHeader,
		IncludeControls:     value.IncludeControls,
	}
	if value.Measurements != nil {
		result.Measurements = make([]*owonmodel.MeasurementSelector, len(value.Measurements))
		for index, item := range value.Measurements {
			result.Measurements[index] = MeasurementSelectorFromProto(item)
		}
	}
	return result
}

// StateSnapshotToProto converts native values to wire fields with independent mutable ownership.
//
// Example: an omitted generator snapshot stays nil while screen-header bytes are copied independently.
func StateSnapshotToProto(value *owonmodel.StateSnapshot) *pb.StateSnapshot {
	if value == nil {
		return nil
	}
	result := &pb.StateSnapshot{
		Device:           DeviceInfoToProto(value.Device),
		Measurements:     nil,
		ScreenHeaderJson: slices.Clone(value.ScreenHeaderJSON),
		CapturedAt:       timestamppb.New(value.CapturedAt),
		Channels:         nil,
		Acquisition:      AcquisitionStateToProto(value.Acquisition),
		Horizontal:       HorizontalStateToProto(value.Horizontal),
		Trigger:          TriggerStateToProto(value.Trigger),
		Generator:        GeneratorStateToProto(value.Generator),
		Dmm:              DMMStateToProto(value.DMM),
	}
	if value.Measurements != nil {
		result.Measurements = make([]*pb.Measurement, len(value.Measurements))
		for index, item := range value.Measurements {
			result.Measurements[index] = MeasurementToProto(item)
		}
	}
	if value.Channels != nil {
		result.Channels = make([]*pb.ChannelState, len(value.Channels))
		for index, item := range value.Channels {
			result.Channels[index] = ChannelStateToProto(item)
		}
	}
	return result
}
