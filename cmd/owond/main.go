// Command owond exposes one serial-selected OWON instrument through gRPC.
//
// Example: owond --serial 25061855 listens on the default local Unix socket.
package main

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/signal"
	"syscall"
	"time"

	"github.com/facebookincubator/go-belt"
	"github.com/facebookincubator/go-belt/tool/logger"
	"github.com/spf13/cobra"
	"github.com/xaionaro-go/owon/pkg/owonctl"
	"github.com/xaionaro-go/owon/pkg/owonlog"
	"github.com/xaionaro-go/owon/pkg/owonrpc"
	pb "github.com/xaionaro-go/owon/pkg/owonrpc/autogenerated"
	"github.com/xaionaro-go/owon/pkg/owonrpc/owonserver"
	"github.com/xaionaro-go/owon/pkg/owonsession"
	"github.com/xaionaro-go/owon/pkg/owonusb"
	"google.golang.org/grpc"
)

const (
	// shutdownTimeout bounds the caller's wait for session cleanup.
	//
	// Example: expiry does not claim synchronous native close has completed.
	shutdownTimeout = 5 * time.Second
)

// closeSession retains context values during an independently bounded shutdown.
//
// Example: a canceled serving context still supplies fields to USB cleanup.
func closeSession(
	ctx context.Context,
	session *owonsession.Session,
) (_err error) {
	if session == nil {
		return nil
	}
	if ctx == nil {
		return &ErrConfiguration{Field: "context", Reason: "must not be nil"}
	}
	ctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), shutdownTimeout)
	defer cancel()
	logger.Tracef(ctx, "closeSession")
	// traceClose records the cleanup result after native ownership has settled.
	//
	// Example: a close failure remains observable alongside its returned error.
	defer func() { logger.Tracef(ctx, "/closeSession: %v", _err) }()

	return session.CloseContext(ctx)
}

// run executes native Cobra parsing, help, validation, and daemon ownership.
//
// Example: --help succeeds without loading credentials or discovering hardware.
func run(
	ctx context.Context,
	arguments []string,
	output io.Writer,
	logOutput io.Writer,
) error {
	if ctx == nil {
		return &ErrConfiguration{Field: "context", Reason: "must not be nil"}
	}
	diagnostics, err := owonctl.NewDiagnosticWriter(output)
	if err != nil {
		return err
	}
	handler := &daemonCommand{LogOutput: logOutput}
	command := handler.Command()
	command.SetOut(diagnostics)
	command.SetErr(diagnostics)
	command.SetArgs(arguments)

	return diagnostics.Join(command.ExecuteContext(ctx))
}

// Execute installs contextual logging before opening hardware and serving gRPC.
//
// Example: an absent serial still emits startup before USB selection fails.
func (handler *daemonCommand) Execute(
	command *cobra.Command,
	_ []string,
) (_err error) {
	config := handler.Config
	logConfig := owonlog.Config{Level: config.LogLevel, Service: "owond"}
	ctx, err := owonlog.WithContext(command.Context(), logConfig, handler.LogOutput)
	if err != nil {
		return err
	}
	ctx = belt.WithField(ctx, "requested_serial", config.Serial)
	ctx = belt.WithField(ctx, "grpc_endpoint", handler.Listen)
	logger.Tracef(ctx, "Execute")
	// traceExecute reports the entire lifetime result without discarding cleanup failures.
	//
	// Example: failed USB discovery produces one contextual exit trace.
	defer func() { logger.Tracef(ctx, "/Execute: %v", _err) }()
	logger.Infof(ctx, "starting OWON daemon")

	serverOptions := owonserver.GRPCServerOptions()
	if config.TLSCert != "" {
		tlsCredentials, tlsErr := owonrpc.LoadServerTLSCredentials(owonrpc.ServerTLSConfig{
			CertificateFile: config.TLSCert, PrivateKeyFile: config.TLSKey, ClientCAFile: config.ClientCA,
			AllowedClientSANs: config.ClientSANs, AllowedClientFingerprints: config.ClientFingerprints,
		})
		if tlsErr != nil {
			return fmt.Errorf("load server TLS credentials: %w", tlsErr)
		}
		serverOptions = append(serverOptions, grpc.Creds(tlsCredentials))
	}

	backend, err := owonusb.Open(ctx, config.usbConfig())
	if err != nil {
		return err
	}
	config.Serial = backend.Serial()
	ctx = belt.WithField(ctx, "serial", config.Serial)
	service, session, err := composeService(ctx, backend,
		owonsession.Config{ExpectedSerial: config.Serial, OperationTimeout: config.DeviceTimeout},
		owonserver.ServerConfig{MaxActiveSubscriptions: config.MaximumSubscriptions})
	if err != nil {
		return err
	}
	if config.KeepAwake {
		if err := service.EnsureKeepAwake(ctx); err != nil {
			return rejectStartup(ctx, sessionCleanup{Session: session}, fmt.Errorf("enable keep-awake policy: %w", err))
		}
	}
	rpcLogging, err := owonserver.NewRPCLogging(logConfig, handler.LogOutput, config.Serial)
	if err != nil {
		return rejectStartup(ctx, sessionCleanup{Session: session}, err)
	}
	serverOptions = append(serverOptions, grpc.StatsHandler(rpcLogging))
	grpcServer := grpc.NewServer(serverOptions...)
	pb.RegisterOwonServiceServer(grpcServer, service)

	return serveInstrument(ctx, grpcServer, session, config)
}

// serveInstrument releases the listener and hardware before reporting shutdown.
//
// Example: a bind failure still closes the session and retains both error causes.
func serveInstrument(
	ctx context.Context,
	grpcServer *grpc.Server,
	session *owonsession.Session,
	config options,
) error {
	var errs []error
	errs = append(errs, serveGRPC(ctx, grpcServer, config))
	errs = append(errs, closeSession(ctx, session))
	resultErr := errors.Join(errs...)
	if resultErr == nil {
		logger.Infof(ctx, "gRPC server stopped; instrument closed")
	}

	return resultErr
}

// main selects process streams and translates terminal errors to a nonzero exit.
//
// Example: systemd receives an error exit when USB discovery fails.
func main() {
	ctx, err := owonlog.WithContext(context.Background(), owonlog.Config{Level: logger.LevelInfo, Service: "owond"}, os.Stderr)
	if err != nil {
		panic(err)
	}
	ctx, stop := signal.NotifyContext(ctx, os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, os.Args[1:], os.Stdout, os.Stderr); err != nil {
		logger.Fatalf(ctx, "%v", err)
	}
}
