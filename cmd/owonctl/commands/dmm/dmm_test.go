// TestCommandAcceptsSupportedDMMPatches checks friendly spellings retain typed range presence.
//
// Example: mV becomes DMM_RANGE_MV without inventing an automatic-range setting.
func TestCommandAcceptsSupportedDMMPatches(t *testing.T) {
	for _, test := range []struct {
		Token string
		Range pb.DmmRange
	}{
		{Token: "ON", Range: pb.DmmRange_DMM_RANGE_ON},
		{Token: " mV ", Range: pb.DmmRange_DMM_RANGE_MV},
		{Token: "v", Range: pb.DmmRange_DMM_RANGE_V},
	} {
		request, err := buildDMMRequest(dmmOptions{RangeValue: test.Token}, dmmFlagPresence{RangeValue: true})
		require.NoError(t, err)
		require.NotNil(t, request.Range)
		require.Equal(t, test.Range, *request.Range)
		require.Nil(t, request.AutoRange)
	}
	for _, function := range []string{"voltage", "current"} {
		for _, currentType := range []string{"ac", "dc"} {
			prepared, err := buildDMMRequest(dmmOptions{Function: function, CurrentType: currentType, Relative: false, AutoRange: true}, dmmFlagPresence{Function: true, CurrentType: true, Relative: true, AutoRange: true})
			require.NoError(t, err)
			require.NotNil(t, prepared)
		}
	}
}
