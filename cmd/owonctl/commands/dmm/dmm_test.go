// TestParseDMMFunctionAcceptsSupportedFunctions verifies every documented DMM mode.
//
// Example: capacitance is accepted as a typed function selection.
func TestParseDMMFunctionAcceptsSupportedFunctions(t *testing.T) {
	t.Parallel()

	tests := []struct {
		Name  string
		Value string
		Want  pb.DmmFunction
	}{
		{Name: "voltage", Value: "voltage", Want: pb.DmmFunction_DMM_FUNCTION_VOLTAGE},
		{Name: "current", Value: "current", Want: pb.DmmFunction_DMM_FUNCTION_CURRENT},
		{Name: "resistance", Value: "resistance", Want: pb.DmmFunction_DMM_FUNCTION_RESISTANCE},
		{Name: "capacitance", Value: "capacitance", Want: pb.DmmFunction_DMM_FUNCTION_CAPACITANCE},
		{Name: "diode", Value: "diode", Want: pb.DmmFunction_DMM_FUNCTION_DIODE},
		{Name: "continuity", Value: "continuity", Want: pb.DmmFunction_DMM_FUNCTION_CONTINUITY},
	}
	for _, test := range tests {
		t.Run(test.Name,
			// verifyDMMFunctionCase checks one documented DMM function spelling.
			//
			// Example: the capacitance spelling maps to the protobuf enum.
			func(t *testing.T) {
				got, err := parseDMMFunction(test.Value)
				require.NoError(t, err)
				require.Equal(t, test.Want, got)
			})
	}
}

