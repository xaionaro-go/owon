// TestBuildDMMRequestPreservesExplicitCapacitanceSelection verifies presence-aware patching.
//
// Example: selecting capacitance does not accidentally overwrite relative or range settings.
func TestBuildDMMRequestPreservesExplicitCapacitanceSelection(t *testing.T) {
	t.Parallel()

	request, err := buildDMMRequest(dmmOptions{Function: "capacitance"}, dmmFlagPresence{Function: true})
	require.NoError(t, err)
	require.NotNil(t, request)
	require.Equal(t, pb.DmmFunction_DMM_FUNCTION_CAPACITANCE, *request.Function)
	require.Nil(t, request.CurrentType)
	require.Nil(t, request.Relative)
	require.Nil(t, request.Range)
	require.Nil(t, request.AutoRange)
}

