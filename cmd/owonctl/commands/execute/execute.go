// Package execute implements the owonctl execute command.
//
// Example: `owonctl execute --mode ascii '*IDN?'` prints the instrument's identity response.
package execute

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"github.com/facebookincubator/go-belt"
	"github.com/facebookincubator/go-belt/tool/logger"
	"github.com/spf13/cobra"
	"github.com/xaionaro-go/owon/pkg/owonctl"
	"github.com/xaionaro-go/owon/pkg/owonrpc"
	pb "github.com/xaionaro-go/owon/pkg/owonrpc/autogenerated"
	"github.com/xaionaro-go/owon/pkg/owonrpc/owonclient"
)

// commandHandler holds command inputs and shared connection policy.
//
// Example: Cobra populates command values before execution.
type commandHandler struct {
	Config *owonctl.ClientConfig
	Mode   string
}

// NewCommand constructs this independently registered Cobra command.
//
// Example: the executable adds the command to its root.
func NewCommand(config *owonctl.ClientConfig) *cobra.Command {
	handler := &commandHandler{Config: config}
	command := &cobra.Command{Use: "execute SCPI", Short: "Execute one explicitly framed SCPI command", Args: cobra.ExactArgs(1), RunE: handler.run}
	command.Flags().StringVar(&handler.Mode, "mode", "ascii", "none, ascii, binary, or length-prefixed")

	return command
}

// run validates inputs, owns the command connection, and writes the result.
//
// Example: invalid requests fail before a connection is constructed.
func (handler *commandHandler) run(
	command *cobra.Command,
	arguments []string,
) (_err error) {
	mode, err := responseMode(handler.Mode)
	if err != nil {
		return err
	}
	request := &pb.ExecuteRequest{Command: arguments[0], ResponseMode: mode}
	if _, err := owonrpc.CommandFromProto(request); err != nil {
		return fmt.Errorf("prepare execute: %w", err)
	}

	config, err := handler.Config.ConnectionConfig()
	if err != nil {
		return err
	}

	ctx, cancel := context.WithTimeout(command.Context(), handler.Config.Timeout)
	defer cancel()
	ctx = belt.WithField(ctx, "command", "execute")
	logger.Tracef(ctx, "execute")
	// traceResult reports completion after command-owned cleanup.
	//
	// Example: operation and cleanup errors remain visible at trace level.
	defer func() { logger.Tracef(ctx, "/execute: %v", _err) }()

	connection, err := owonclient.NewConnection(ctx, config)
	if err != nil {
		return err
	}

	// closeConnection retains independent cleanup failures.
	//
	// Example: an RPC failure cannot hide a connection close failure.
	defer func() { _err = errors.Join(_err, connection.Close()) }()

	logger.Debugf(ctx, "executing execute")
	response, err := connection.Client().Execute(ctx, request)
	if err != nil {
		return err
	}
	if _, err := command.OutOrStdout().Write(response); err != nil {
		return fmt.Errorf("write command response: %w", err)
	}
	if request.ResponseMode == pb.ResponseMode_RESPONSE_MODE_ASCII_LINE {
		if _, err := fmt.Fprintln(command.OutOrStdout()); err != nil {
			return fmt.Errorf("write command response terminator: %w", err)
		}
	}
	return nil
}

// responseMode translates the CLI spelling into the explicit protobuf framing enum.
//
// Example: `length-prefixed` selects OWON_LENGTH_PREFIXED framing.
func responseMode(value string) (pb.ResponseMode, error) {
	switch strings.ToLower(value) {
	case "none":
		return pb.ResponseMode_RESPONSE_MODE_NONE, nil
	case "ascii":
		return pb.ResponseMode_RESPONSE_MODE_ASCII_LINE, nil
	case "binary", "length-prefixed":
		return pb.ResponseMode_RESPONSE_MODE_OWON_LENGTH_PREFIXED, nil
	default:
		return pb.ResponseMode_RESPONSE_MODE_UNSPECIFIED, &owonctl.ErrCommandArguments{Command: "execute", Reason: fmt.Sprintf("unsupported response mode %q", value)}
	}
}
