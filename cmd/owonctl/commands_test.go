// rpcInvocation records requests received over a real gRPC transport.
//
// Example: literal --help must reach Execute without becoming a help request.
type rpcInvocation struct {
	Method  string
	Request proto.Message
}

// commandService supplies deterministic instrument replies at the remote RPC boundary.
//
// Example: command formatting and error propagation run through the real gRPC client.
type commandService struct {
	Calls            chan rpcInvocation
	FailMethod       string
	MeasuredFunction *pb.DmmFunction
	Connections      atomic.Int64
}

// intercept responds to the CLI's verified RPCs and rejects unexpected methods.
//
// Example: SetDmm and GetDmmMeasurement remain two independently observable calls.
func (service *commandService) intercept(
	_ context.Context,
	request any,
	info *grpc.UnaryServerInfo,
	_ grpc.UnaryHandler,
) (any, error) {
	method := info.FullMethod[strings.LastIndex(info.FullMethod, "/")+1:]
	message, ok := request.(proto.Message)
	if !ok {
		return nil, status.Error(codes.Internal, "unexpected non-protobuf request")
	}
	service.Calls <- rpcInvocation{Method: method, Request: message}
	if method == service.FailMethod {
		return nil, status.Error(codes.Unavailable, "instrument unavailable")
	}
	switch method {
	case "GetDeviceInfo":
		return &pb.DeviceInfo{Model: "HDS2202S", Serial: "fixture"}, nil
	case "GetState":
		return &pb.StateSnapshot{Device: &pb.DeviceInfo{Serial: "fixture"}}, nil
	case "Execute":
		executeRequest, ok := request.(*pb.ExecuteRequest)
		if !ok {
			return nil, status.Error(codes.Internal, "unexpected execute request")
		}
		return &pb.ExecuteResponse{Data: []byte(executeRequest.Command)}, nil
	case "GetDmmMeasurement":
		return &pb.DmmMeasurement{Value: 2.5, Unit: "V", Function: service.MeasuredFunction}, nil
	case "GetWaveform":
		return &pb.Waveform{Data: []byte{1, 2, 3}}, nil
	case "Run", "Stop", "Single", "SetDmm":
		return &pb.CommandResult{AppliedAt: timestamppb.New(time.Unix(1, 0))}, nil
	default:
		return nil, status.Error(codes.Unimplemented, "unexpected method "+method)
	}
}

// commandServer owns a test listener and publishes its serving result.
//
// Example: cleanup waits for Serve to finish before ending the test.
type commandServer struct {
	Server   *grpc.Server
	Listener net.Listener
	Result   chan error
}

// commandListener counts accepted connections independently of RPC dispatch.
//
// Example: invalid preparation must not open a transport even if it sends no RPC.
type commandListener struct {
	net.Listener
	Connections *atomic.Int64
}

// Accept records each successfully opened client transport.
//
// Example: listener shutdown does not increment the connection counter.
func (listener commandListener) Accept() (net.Conn, error) {
	connection, err := listener.Listener.Accept()
	if err == nil {
		listener.Connections.Add(1)
	}
	return connection, err
}

// serve runs the real gRPC server until cleanup stops it.
//
// Example: observability.Go supplies the lifecycle context without a raw goroutine.
func (server commandServer) serve(_ context.Context) {
	err := server.Server.Serve(server.Listener)
	if errors.Is(err, grpc.ErrServerStopped) {
		err = nil
	}
	server.Result <- err
}

// startCommandService starts a loopback server with deterministic device replies.
//
// Example: both in-process application tests and built CLI processes use its endpoint.
func startCommandService(
	t *testing.T,
	service *commandService,
) string {
	t.Helper()
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	server := grpc.NewServer(grpc.UnaryInterceptor(service.intercept))
	pb.RegisterOwonServiceServer(server, &pb.UnimplementedOwonServiceServer{})
	loop := commandServer{Server: server, Listener: commandListener{Listener: listener, Connections: &service.Connections}, Result: make(chan error, 1)}
	observability.Go(t.Context(), loop.serve)
	t.Cleanup(
		// stopServer joins the serving goroutine so no listener leaks into another test.
		//
		// Example: every command server terminates even after an assertion failure.
		func() {
			server.Stop()
			require.NoError(t, <-loop.Result)
		},
	)
	return "tcp://" + listener.Addr().String()
}

// commandCase describes one public command's request and observable response.
//
// Example: execute returns raw bytes while waveform returns protobuf JSON.
type commandCase struct {
	Name      string
	Arguments []string
	Method    string
	Contains  string
}

// commandCases lists all eight command contracts without duplicating their implementation.
//
// Example: state must issue GetState and expose the returned device serial.
func commandCases() []commandCase {
	return []commandCase{
		{Name: "info", Method: "GetDeviceInfo", Contains: "fixture"},
		{Name: "state", Method: "GetState", Contains: "fixture"},
		{Name: "execute", Arguments: []string{"--", "--help"}, Method: "Execute", Contains: "--help\n"},
		{Name: "run", Method: "Run", Contains: "applied_at"},
		{Name: "stop", Method: "Stop", Contains: "applied_at"},
		{Name: "single", Method: "Single", Contains: "applied_at"},
		{Name: "dmm", Method: "GetDmmMeasurement", Contains: "2.5"},
		{Name: "waveform", Method: "GetWaveform", Contains: "AQID"},
	}
}

// commandOutputFailure models a broken response destination after successful RPC execution.
//
// Example: every command must return this cause instead of silently losing its response.
type commandOutputFailure struct{ Cause error }

// Write rejects output and preserves the specific underlying cause.
//
// Example: errors.Is can classify the failure through application cleanup.
func (writer commandOutputFailure) Write(_ []byte) (int, error) { return 0, writer.Cause }

// TestEveryCommandPublicPath verifies success, daemon failures, help, invalid input, and failed output.
//
// Example: a failed Run RPC emits no successful command-result JSON.
func TestEveryCommandPublicPath(t *testing.T) {
	for _, test := range commandCases() {
		t.Run(test.Name,
			// checkCommand exercises both successful and failing public application paths.
			//
			// Example: unavailable service errors retain their gRPC status code.
			func(t *testing.T) {
				service := &commandService{Calls: make(chan rpcInvocation, 16)}
				endpoint := startCommandService(t, service)
				var output bytes.Buffer
				application, err := newApplication(&output)
				require.NoError(t, err)
				arguments := append([]string{"--address", endpoint, test.Name}, test.Arguments...)
				require.NoError(t, application.Run(t.Context(), arguments))
				require.Contains(t, output.String(), test.Contains)
				call := <-service.Calls
				require.Equal(t, test.Method, call.Method)
				if test.Name == "execute" {
					require.Equal(t, "--help", call.Request.(*pb.ExecuteRequest).Command)
				}
				if test.Name == "state" {
					require.Len(t, call.Request.(*pb.GetStateRequest).Measurements, 14)
				}
				require.Empty(t, service.Calls)
				output.Reset()
				require.NoError(t, application.Run(t.Context(), []string{"--address", "invalid", test.Name, "--help"}))
				require.Contains(t, output.String(), "owonctl "+test.Name)
				require.Empty(t, service.Calls)
				err = application.Run(t.Context(), []string{test.Name, "--unknown"})
				var parseError *owonctl.ErrFlagParse
				require.ErrorAs(t, err, &parseError)
				cause := errors.New("output closed")
				application, err = newApplication(commandOutputFailure{Cause: cause})
				require.NoError(t, err)
				require.ErrorIs(t, application.Run(t.Context(), arguments), cause)
				require.Equal(t, test.Method, (<-service.Calls).Method)
				failingService := &commandService{Calls: make(chan rpcInvocation, 2), FailMethod: test.Method}
				failingEndpoint := startCommandService(t, failingService)
				output.Reset()
				application, err = newApplication(&output)
				require.NoError(t, err)
				arguments[1] = failingEndpoint
				err = application.Run(t.Context(), arguments)
				require.Equal(t, codes.Unavailable, status.Code(err))
				require.Empty(t, output.String())
			},
		)
	}
}

// TestDMMPreservesObservedMetadata ensures requested intent never overwrites the reply.
//
// Example: selecting capacitance cannot label a concurrently returned voltage measurement as capacitance.
func TestDMMPreservesObservedMetadata(t *testing.T) {
	for _, measured := range []*pb.DmmFunction{nil, pb.DmmFunction_DMM_FUNCTION_VOLTAGE.Enum()} {
		service := &commandService{Calls: make(chan rpcInvocation, 4), MeasuredFunction: measured}
		endpoint := startCommandService(t, service)
		var output bytes.Buffer
		application, err := newApplication(&output)
		require.NoError(t, err)
		require.NoError(t, application.Run(t.Context(), []string{"--address", endpoint, "dmm", "--function", "capacitance"}))
		require.Equal(t, "SetDmm", (<-service.Calls).Method)
		require.Equal(t, "GetDmmMeasurement", (<-service.Calls).Method)
		require.NotContains(t, output.String(), "CAPACITANCE")
		if measured == nil {
			require.NotContains(t, output.String(), "function")
		} else {
			require.Contains(t, output.String(), "VOLTAGE")
		}
	}
}

// TestDMMPatchesPreservePresenceAndStopOnFailedConfiguration checks optional request fields.
//
// Example: a failed SetDmm must prevent a subsequent measurement from looking successful.
func TestDMMPatchesPreservePresenceAndStopOnFailedConfiguration(t *testing.T) {
	service := &commandService{Calls: make(chan rpcInvocation, 4)}
	endpoint := startCommandService(t, service)
	application, err := newApplication(io.Discard)
	require.NoError(t, err)
	arguments := []string{"--address", endpoint, "dmm", "--function", "voltage", "--current-type", "dc", "--relative=false", "--range", "mV", "--auto-range"}
	require.NoError(t, application.Run(t.Context(), arguments))
	call := <-service.Calls
	require.Equal(t, "SetDmm", call.Method)
	request, ok := call.Request.(*pb.SetDmmRequest)
	require.True(t, ok)
	require.Equal(t, pb.DmmFunction_DMM_FUNCTION_VOLTAGE, *request.Function)
	require.Equal(t, pb.DmmCurrentType_DMM_CURRENT_TYPE_DC, *request.CurrentType)
	require.Equal(t, pb.DmmRange_DMM_RANGE_MV, *request.Range)
	require.NotNil(t, request.Relative)
	require.False(t, *request.Relative)
	require.True(t, *request.AutoRange)
	require.Equal(t, "GetDmmMeasurement", (<-service.Calls).Method)
	failing := &commandService{Calls: make(chan rpcInvocation, 4), FailMethod: "SetDmm"}
	arguments[1] = startCommandService(t, failing)
	require.Equal(t, codes.Unavailable, status.Code(application.Run(t.Context(), arguments)))
	require.Equal(t, "SetDmm", (<-failing.Calls).Method)
	require.Empty(t, failing.Calls)
	err = application.Run(t.Context(), []string{"dmm", "--current-type", "invalid"})
	require.ErrorContains(t, err, "unsupported current type")
	err = application.Run(t.Context(), []string{"execute", "--mode", "invalid", "*IDN?"})
	require.ErrorContains(t, err, "unsupported response mode")
}

// TestBuiltCLICommands exercises every command through an actual compiled process and TCP gRPC.
//
// Example: offline help succeeds while literal --help reaches the deterministic service.
func TestBuiltCLICommands(t *testing.T) {
	binary := filepath.Join(t.TempDir(), "owonctl")
	build := exec.CommandContext(t.Context(), "go", "build", "-o", binary, ".")
	buildOutput, err := build.CombinedOutput()
	require.NoError(t, err, "%s", buildOutput)
	service := &commandService{Calls: make(chan rpcInvocation, 16)}
	endpoint := startCommandService(t, service)
	for _, test := range commandCases() {
		arguments := append([]string{"--address", endpoint, "--log-level", "trace", test.Name}, test.Arguments...)
		process := exec.CommandContext(t.Context(), binary, arguments...)
		var diagnostics bytes.Buffer
		process.Stderr = &diagnostics
		output, err := process.Output()
		require.NoError(t, err, "%s", output)
		require.Contains(t, string(output), test.Contains)
		if test.Name != "execute" {
			require.True(t, json.Valid(output), "%s", output)
		}
		require.Contains(t, diagnostics.String(), "service=owonctl")
		require.Contains(t, diagnostics.String(), "command="+test.Name)
		require.Contains(t, diagnostics.String(), "level=trace")
		require.Contains(t, diagnostics.String(), "executing "+test.Name)
		require.Equal(t, test.Method, (<-service.Calls).Method)
		t.Logf("%s: success, expected RPC and output", test.Name)
	}
	for _, arguments := range [][]string{nil, {"--help"}, {"info", "--help"}, {"state", "--help"}, {"execute", "--help"}, {"run", "--help"}, {"stop", "--help"}, {"single", "--help"}, {"dmm", "--help"}, {"waveform", "--help"}} {
		output, err := exec.CommandContext(t.Context(), binary, arguments...).CombinedOutput()
		require.NoError(t, err, "%s", output)
		require.Contains(t, string(output), "Usage:")
		require.Empty(t, service.Calls)
	}
	output, err := exec.CommandContext(t.Context(), binary, "--address", "unix:///nonexistent/owond.sock", "info", "--help").CombinedOutput()
	require.NoError(t, err, "%s", output)
	require.Contains(t, string(output), "owonctl info [flags]")
	output, err = exec.CommandContext(t.Context(), binary, "--address", "invalid", "dmm", "--range", "--help").CombinedOutput()
	require.Error(t, err)
	require.Contains(t, string(output), "unsupported range")
	require.NotContains(t, string(output), "Usage:")
	require.Empty(t, service.Calls)
	connections := service.Connections.Load()
	for _, global := range [][]string{
		{"--address", "invalid"},
		{"--address", "tcp://192.0.2.1:50051", "--ca", "/nonexistent/ca", "--cert", "/nonexistent/cert", "--key", "/nonexistent/key", "--server-name", "scope"},
		{"--address", endpoint},
	} {
		for _, invocation := range invalidInvocations() {
			arguments := append(append([]string(nil), global...), invocation...)
			output, err := exec.CommandContext(t.Context(), binary, arguments...).CombinedOutput()
			require.Error(t, err, "%q", invocation)
			require.NotContains(t, string(output), "invalid endpoint")
			require.NotContains(t, string(output), "load client TLS")
			require.Contains(t, string(output), invocation[0])
			require.Empty(t, service.Calls)
			require.Equal(t, connections, service.Connections.Load())
		}
	}
	for _, measured := range []*pb.DmmFunction{nil, pb.DmmFunction_DMM_FUNCTION_VOLTAGE.Enum()} {
		measurementService := &commandService{Calls: make(chan rpcInvocation, 4), MeasuredFunction: measured}
		measurementEndpoint := startCommandService(t, measurementService)
		output, err := exec.CommandContext(t.Context(), binary, "--address", measurementEndpoint, "dmm", "--function", "capacitance").CombinedOutput()
		require.NoError(t, err, "%s", output)
		require.Equal(t, "SetDmm", (<-measurementService.Calls).Method)
		require.Equal(t, "GetDmmMeasurement", (<-measurementService.Calls).Method)
		require.NotContains(t, string(output), "CAPACITANCE")
		if measured == nil {
			require.NotContains(t, string(output), "function")
		} else {
			require.Contains(t, string(output), "VOLTAGE")
		}
	}
	application, err := newApplication(io.Discard)
	require.NoError(t, err)
	require.NoError(t, application.Run(t.Context(), []string{"--help"}))
}
